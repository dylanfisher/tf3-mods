"""Writes the DEV DoF probe's environment files (mods/square_photo_dof_probe/content/environments/).

Each file is a copy of a base climate's env file (.cache/game/base/content/climates/<c>/<c>.env.lua) with only
three changes: light.latitude + 2*pi*mode (the probe shader's on/off channel, see shader_files/.../ssr_apply.fs),
the name, isToolEnvironment = true, plus texture names made absolute ("sun.dds" -> "::/climates/<c>/sun.dds",
"/climates/shared/x" -> "::/climates/shared/x"), since relative names resolve next to the mod's file.

Run: uv run plans/square_photo_dof_probe/gen_envs.py [--check]  (re-run after a game update)
"""
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / ".cache/game/base/content/climates"
OUT = ROOT / "mods/square_photo_dof_probe/content/environments"
CLIMATES = ["dry", "temperate", "tropical", "subarctic"]
MODES = {1: "tilt", 2: "dof", 3: "dof_shallow", 4: "debug"}


def render(climate: str, mode: int, key: str) -> str:
    src = (BASE / climate / f"{climate}.env.lua").read_text(encoding="utf-8")
    m = re.search(r"latitude = ([-0-9.e]+),", src)
    if not m:
        raise SystemExit(f"{climate}: no latitude line")
    lat = float(m.group(1))
    new_lat = lat + 2 * math.pi * mode
    out = src.replace(m.group(0), f"latitude = {new_lat!r}, -- sqdof: {lat!r} + 2 pi * {mode}", 1)
    out, n = re.subn(r'name = _\("[^"]*"\),', f'name = "SQDOF {key} ({climate})",\n\t\tisToolEnvironment = true,', out, count=1)
    if n != 1:
        raise SystemExit(f"{climate}: no name line")

    def fix(mt: re.Match) -> str:
        k, v = mt.group(1), mt.group(2)
        if v == "" or v.startswith("::"):
            return mt.group(0)
        if v.startswith("/"):
            return f'{k} = "::{v}"'
        return f'{k} = "::/climates/{climate}/{v}"'

    out = re.sub(r'(fileName|depthColorTex|normalTex|waveFoamTex) = "([^"]*)"', fix, out)
    head = (f"-- DEV square_photo_dof_probe: base climates/{climate}/{climate}.env.lua with light.latitude + 2 pi * {mode}\n"
            f"-- (probe shader mode {mode} = {key}), name, isToolEnvironment, absolute texture names.\n"
            f"-- Generated by plans/square_photo_dof_probe/gen_envs.py: don't edit. Never upload.\n")
    return head + out


def main() -> int:
    check = "--check" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    drift = 0
    for c in CLIMATES:
        for mode, key in MODES.items():
            p = OUT / f"sqdof_{c}_{key}.env.lua"
            text = render(c, mode, key)
            if check:
                if not p.exists() or p.read_text(encoding="utf-8") != text:
                    print(f"drift: {p.relative_to(ROOT)}")
                    drift += 1
            else:
                p.write_text(text, encoding="utf-8")
    print(f"{'checked' if check else 'wrote'} {len(CLIMATES) * len(MODES)} files, drift {drift}")
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
