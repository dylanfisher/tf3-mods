// Writes the old lab page's gen.js from the site lab's TypeScript port (2026-10-15, NEXT_PHASE_BRIEF 60): gen.js was a
// hand-kept copy of site/src/mods/square_organic_towns/namelab/gen.ts without the types; now it is generated, so the
// two never drift. Node 22.13+ (module.stripTypeScriptTypes). Run after every change to gen.ts:
//   node plans/square_organic_towns/names/gen_js.mjs && node plans/square_organic_towns/names/check_port.js
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stripTypeScriptTypes } from "node:module";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TS = path.resolve(HERE, "../../../site/src/mods/square_organic_towns/namelab/gen.ts");
const src = fs.readFileSync(TS, "utf8");
let js = stripTypeScriptTypes(src, { mode: "strip" });
const EXPORT = "export { create, rng, b, u };";
if (!js.includes(EXPORT)) throw new Error("gen.ts: no `" + EXPORT + "` line");
js = js.replace(EXPORT, "const api = { create, rng, b, u };\n" +
  "if (typeof module !== 'undefined' && module.exports) module.exports = api;\nroot.NameGen = api;");
const head = "// GENERATED by plans/square_organic_towns/names/gen_js.mjs from site/src/mods/square_organic_towns/namelab/gen.ts\n" +
  "// (the Name lab's port of ot_placename.lua) for the old lab page (index.html, check_port.js). Do not edit.\n";
js = head + "(function (root) {\n'use strict';\n" + js + "\n})(typeof window !== 'undefined' ? window : globalThis);\n";
fs.writeFileSync(path.join(HERE, "gen.js"), js);
console.log("gen.js: " + js.length + " bytes from gen.ts");
