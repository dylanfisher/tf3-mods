--- The dev overrides present in params (geom.DEV_KEYS), or nil if there are none.
function geom.readDev(params)
	local dev
	for name, key in pairs(geom.DEV_KEYS) do
		local v = tonumber(params[key])
		local range = geom.DEV_RANGES[name]
		if v and v == v and v >= range[1] and v <= range[2] and (not range[3] or v == math.floor(v)) then
			dev = dev or {}
			dev[name] = v
		end
	end
	return dev
end

-- Tuning table lookups (square_roundabouts_tuning.lua) ------------------------------------------

--- Tuning key of a main-entry spec: the param indices of every axis the probe search varies,
-- except the radius ("shape,lanes,arms,splitter,centre,armType,tram,direction"). Arms None builds
-- no splitter legs (a through road's axis arms never get them), so it uses the splitter-off key.
-- Road + traffic lights has the Road geometry (Phase 5c), so it shares Road's key. A through road
-- other than the arm road (geom.throughOwnRoad) appends its arm road index as a ninth field
-- (Phase 5f: the p5_hamburger_radius search); geom.basePatternKey is the key without it.
function geom.basePatternKey(spec)
	local splitter = spec.layout == #geom.ARM_LAYOUTS and geom.SPLITTER_OFF or spec.splitter
	local centre = spec.centre == geom.CENTRE_ROAD_LIGHTS and geom.CENTRE_ROAD or spec.centre
	return table.concat({ spec.shape, spec.lanes, spec.layout, splitter, centre, spec.armType, spec.tram, spec.direction }, ",")
end

function geom.patternKey(spec)
	local key = geom.basePatternKey(spec)
	if geom.throughOwnRoad(spec) then key = key .. "," .. spec.throughType end
	return key
end

--- Whether the spec builds a road (not a tram line) through the centre: Road or Road + traffic lights.
function geom.centreRoad(spec)
	return spec.centre == geom.CENTRE_ROAD or spec.centre == geom.CENTRE_ROAD_LIGHTS
end

--- Whether a road through the centre uses another template than the arms (Phase 5c "Through
-- road"). The tuning table has radii for such layouts only where the probe searched them (their
-- own pattern, geom.patternKey); elsewhere the arm-road pattern's radius is only a floor there
-- (geom.engineRadius), and the offline growth rule decides.
function geom.throughOwnRoad(spec)
	return geom.centreRoad(spec) and spec.throughType ~= nil and spec.throughType ~= spec.armType
end

-- The cell of a radius pattern for the chosen radius (geom.radiusFloor), or nil.
local function radiusCell(key, radius)
	local t = geom.tuning.radius and geom.tuning.radius[key]
	if not t then return nil end
	local from
	for r0 in pairs(t) do
		if r0 <= radius and (not from or r0 > from) then from = r0 end
	end
	local v = from and t[from]
	if v and v > 0 and v >= radius then return v end
	return nil
end

--- Engine radius (m) from the tuning table's radius part, or nil: for the pattern, the cell of the
-- largest probed slider radius r0 at or below the chosen one holds the smallest radius the engine
-- accepted searched from r0 (every slider radius in between was rejected). It applies while the
-- chosen radius is at most that; 0 (or no cell, no pattern) = nil, the offline growth rule.
-- With another through road than the arms: its own pattern first, else the arm-road pattern's
-- cell; the second result is true when the cell is the spec's own pattern.
function geom.radiusFloor(spec)
	local v = radiusCell(geom.patternKey(spec), spec.radius)
	if v then return v, true end
	if geom.throughOwnRoad(spec) then
		v = radiusCell(geom.basePatternKey(spec), spec.radius)
		if v then return v, false end
	end
	return nil
end

--- Whether the probe searched the radius of the spec's pattern (the tuning table's radius part has
-- it, or the arm-road pattern with another through road): there the engine judged the offline
-- growth rule's radius (a 0 cell = accepted as grown), so geom.plan keeps the rule it was searched
-- with and leaves out geom.ARM_BEHIND_PLAN (rev 7). The engine accepted plain arms with corners up
-- to 2.1 m behind on 2:1 ovals (Y arms, 1 lane, large arms at 10-12 m). Round and 2:1 rings are
-- searched; the 1.25-1.75:1 ovals never were.
function geom.radiusSearched(spec)
	local t = geom.tuning.radius
	if not t then return false end
	return t[geom.patternKey(spec)] ~= nil or (geom.throughOwnRoad(spec) and t[geom.basePatternKey(spec)] ~= nil)
end

--- Engine-tuned splitter rule for the spec's arm road and ring lanes ("arm,lanes", then "arm"), or nil.
function geom.splitterRule(spec)
	local t = geom.tuning.splitter
	if not t then return nil end
	return t[spec.armType .. "," .. spec.lanes] or t[tostring(spec.armType)]
end

--- Radius floor (m) of the splitter rule for the spec's arms layout, or nil: the smallest radius
-- at which the engine accepted the rule's layout (generator: search_splitter). It applies while
-- the chosen radius is at most that, and only with splitter islands on.
function geom.splitFloor(spec)
	if spec.splitter ~= geom.SPLITTER_ON then return nil end
	local rule = geom.splitterRule(spec)
	local v = rule and rule.floor and rule.floor[spec.layout]
	if v and v >= spec.radius then return v end
	return nil
end

--- Whether the splitter search accepted the rule at its floor for exactly this kind of spec: it
-- probed round rings without a through road or tram tracks, anticlockwise, for the layouts the
-- rule lists as verified (T, 4 and 6 arms where the engine accepted it at a probed radius).
function geom.splitVerified(spec)
	local rule = geom.splitterRule(spec)
	return rule ~= nil and rule.verified ~= nil and rule.verified[spec.layout] == true
		and spec.shape == geom.SHAPE_ROUND and spec.centre == geom.CENTRE_NONE
		and spec.tram == geom.TRAM_OFF and spec.direction == geom.DIRECTION_CCW
end

--- The ring radius the engine data asks for, or nil (the offline growth rule decides): the radius
-- part of the tuning table first (searched per pattern), then the splitter rule's floor.
-- Returns the radius and whether the engine accepted exactly this layout there (a searched
-- pattern, or a verified splitter floor; not a clockwise pattern copied from anticlockwise, nor a
-- floor taken over from another layout or shape), then the source ("radius", "inferred",
-- "splitter" or "floor"; "through": the arm-road pattern's radius with another through road whose
-- own pattern has no cell, Phase 5c).
function geom.engineRadius(spec)
	local r, own = geom.radiusFloor(spec)
	if r then
		if not own then return r, false, "through" end
		local inferred = geom.tuning.inferred and geom.tuning.inferred[geom.patternKey(spec)]
		if inferred then return r, false, "inferred" end
		return r, true, "radius"
	end
	r = geom.splitFloor(spec)
	if r then
		if geom.splitVerified(spec) then return r, true, "splitter" end
		return r, false, "floor"
	end
	return nil
end

--- Arms of the layout, plus the through axis for a centre road/tram.
-- Through axis rule: the first opposite pair of arms (T, 4, 6: east-west). A layout without an
-- opposite pair gets one extra arm opposite its first arm (Y, 5: north-south); with no arms at all
-- the axis runs east-west with two new arms. So "Road/Tram through" always leads somewhere.
-- Returns arms ({deg, phi, index, axis?, added?, splitter?, tram?}) and the axis {i, j} or nil.
function geom.armsFor(spec)
	local layout = geom.ARM_LAYOUTS[spec.layout] or {}
	local arms = {}
	for i, deg in ipairs(layout) do arms[i] = { deg = deg, index = i } end
	local axis
	if spec.centre ~= geom.CENTRE_NONE then
		for i = 1, #arms do
			for j = i + 1, #arms do
				if not axis and math.abs((arms[j].deg - arms[i].deg) % 360 - 180) < 1e-6 then axis = { i, j } end
			end
		end
		if not axis then
			if #arms > 0 then
				arms[#arms + 1] = { deg = (arms[1].deg + 180) % 360, index = #arms + 1, added = true }
				axis = { 1, #arms }
			else
				arms[1] = { deg = 0, index = 1, added = true }
				arms[2] = { deg = 180, index = 2, added = true }
				axis = { 1, 2 }
			end
		end
		arms[axis[1]].axis = true
		arms[axis[2]].axis = true
	end
	for _, arm in ipairs(arms) do
		arm.phi = arm.deg * DEG
		-- the through axis arms join the ring directly so traffic (or the tram) can cross straight
		arm.splitter = spec.splitter == geom.SPLITTER_ON and not arm.axis
		arm.tram = spec.tram == geom.TRAM_ON or (spec.centre == geom.CENTRE_TRAM and arm.axis == true)
	end
	return arms, axis
end

local function legFor(spec)
	return spec.tram == geom.TRAM_ON and geom.LEG_TRAM or geom.LEG
end

--- Splitter fork angle at the split node and leg spread at the ring for the arm road (wider
-- for arms wider than medium, see LEG_WIDE_FROM).
function geom.legShape(spec)
	local extra = math.max(0, geom.ARM_HALF_WIDTH[spec.armType] - geom.LEG_WIDE_FROM)
	-- forkBump: extra fork steps when the split node's junction does not fit (geom.choosePlan)
	local fork = geom.LEG_FORK + extra * geom.LEG_FORK_PER_M + (spec.forkBump or 0) * geom.LEG_FORK_BUMP
	local spread = geom.LEG_SPREAD + extra * geom.LEG_SPREAD_PER_M + (spec.forkBump or 0) * geom.LEG_SPREAD_BUMP
	return math.min(fork, geom.LEG_FORK_MAX), spread
end

--- Every splitter parameter of a spec, layered: the shipped defaults (SPLIT_LENGTH, legShape,
-- legFor, no neck), then the engine-tuned rule (geom.splitterRule), then the dev overrides.
-- A rule's or override's fork and spread replace the width-aware base values; forkBump steps
-- (geom.choosePlan) still add on top. Returns {split, fork (rad), spread, leg = {template,
-- halfWidth}, neck (m, 0 = none), neckType (arm road index or nil)}.
function geom.splitParams(spec)
	local fork, spread = geom.legShape(spec)
	local sp = { split = geom.SPLIT_LENGTH, fork = fork, spread = spread, leg = legFor(spec), neck = 0 }
	local bump = spec.forkBump or 0
	local tramOn = spec.tram == geom.TRAM_ON
	local function apply(src)
		if not src then return end
		if src.split then sp.split = src.split end
		if src.fork then
			local f = src.fork * DEG
			sp.fork = math.min(f + bump * geom.LEG_FORK_BUMP, math.max(geom.LEG_FORK_MAX, f))
		end
		if src.spread then sp.spread = src.spread + bump * geom.LEG_SPREAD_BUMP end
		local legDef = src.leg and geom.DEV_LEGS[src.leg]
		if legDef then sp.leg = tramOn and legDef.tram or legDef.entry end
		if src.neck then sp.neck = src.neck end
		if src.neckType and geom.ARM_TEMPLATES[src.neckType] then sp.neckType = src.neckType end
	end
	apply(geom.splitterRule(spec))
	apply(spec.dev)
	if sp.neck > 0 and not sp.neckType then
		sp.neckType = spec.armType <= 3 and 1 or 4 -- town small / country small
	end
	return sp
end

--- Half width of the road the legs fork from at the split node (the neck, if any, else the arm).
local function forkRoadHalfWidth(spec, sp)
	if sp.neck > 0 then return geom.ARM_HALF_WIDTH[sp.neckType] end
	return geom.ARM_HALF_WIDTH[spec.armType]
end
geom.forkRoadHalfWidth = forkRoadHalfWidth

--- How far the kerb corner between the two-way arm (half width hwArm, from the split node along
-- u) and a leg (centreline points from the split node) lies behind the split node.
function geom.splitBehind(split, u, hwArm, pts, legHw)
	local v = left(u)
	local prev
	for k = 2, #pts do
		local d = norm(sub(pts[k], pts[k - 1]))
		local n = left(d)
		local kerbs = { add(pts[k], scale(n, legHw)), add(pts[k], scale(n, -legHw)) }
		for side = 1, 2 do
			local q = kerbs[side]
			local lat = math.abs(dot(sub(q, split), v))
			if lat >= hwArm then
				-- interpolate between this kerb point and the previous one
				local p = prev and prev[side] or q
				local latP = math.abs(dot(sub(p, split), v))
				local f = (lat - latP) > 1e-9 and (hwArm - latP) / (lat - latP) or 1
				f = math.max(0, math.min(1, f))
				local c = add(p, scale(sub(q, p), f))
				return -dot(sub(c, split), u)
			end
		end
		prev = kerbs
	end
	return math.huge
end

--- Outward direction of a plain arm (no splitter) at angle phi: the ring's normal at the arm's
-- node (radial on a round ring). Splitter arms stay radial from the split node. Phase 3b: radial arms on an oval's flank met the ring up to 35 degrees off square,
-- and a wide arm's kerb corner then lay 7-9 m behind its node at any ring size.
function geom.armDir(a, b, phi)
	return S.ellipseNormal(a, b, S.paramForAngle(a, b, phi))
end

--- Axis of a splitter arm: radial (the layout the engine data was searched with), or the ring
-- normal like a plain arm when spec.splitNormal is set (geom.choosePlan's last fallback, Phase 5f:
-- on a long oval's flank a radial split runs its legs along the ring at any radius).
function geom.splitAxis(spec, a, b, phi)
	if spec.splitNormal then return geom.armDir(a, b, phi) end
	return dir(phi)
end

--- The two splitter legs of an arm (direction phi) on the ring (a, b, half width hw), from the
-- exit node position xPos and the entry node position ePos: exit X -> split, entry split -> E.
-- Legs fork from the split node at +-fork (geom.legShape) and reach the ring nearly parallel to
-- the ring normal at the arm, turned LEG_ENTRY towards the traffic: the entry joins with the
-- circulation, the exit leaves with it, and the two stay apart for the triangle island between them.
function geom.legEdges(spec, a, b, hw, phi, xPos, ePos, sigma, xTag, eTag, splitTag)
	local u = geom.splitAxis(spec, a, b, phi)
	local p0 = S.ellipsePoint(a, b, S.paramForAngle(a, b, phi))
	local sp = geom.splitParams(spec)
	local split = add(p0, scale(u, hw + sp.split))
	-- ring normal at the arm (= u on a round ring; turned on an oval's flank)
	local un = S.ellipseNormal(a, b, S.paramForAngle(a, b, phi))
	local exit, entry = geom.legCurves(u, un, split, sp.fork, xPos, ePos, sigma, xTag, eTag, splitTag)
	return exit, entry, split
end

--- The two leg curves of a splitter (shared by the roundabout and the channelized junction):
-- exit xPos -> split and entry split -> ePos. They leave the split node at +-fork from the arm
-- axis (u, pointing away from the junction) and reach the road they join nearly parallel to its
-- normal un there, turned LEG_ENTRY towards the traffic (sigma: 1 right-hand, -1 left-hand).
function geom.legCurves(u, un, split, fork, xPos, ePos, sigma, xTag, eTag, splitTag)
	local v = left(u)
	local ca, sa = math.cos(fork), math.sin(fork)
	local cg, sg = math.cos(geom.LEG_ENTRY), math.sin(geom.LEG_ENTRY)
	local vn = left(un)
	local entry = S.curveEdge(split, combine(u, -ca, v, sigma * sa), ePos, combine(un, -cg, vn, sigma * sg), splitTag, eTag)
	local exit = S.curveEdge(xPos, combine(un, cg, vn, sigma * sg), split, combine(u, ca, v, sigma * sa), xTag, splitTag)
	return exit, entry
end

--- Centreline points of an edge from its end at the node (fromEnd: the edge ends there).
local function polyline(e, fromEnd, n)
	local pts = {}
	for k = 0, n do
		local s = fromEnd and (1 - k / n) or (k / n)
		pts[#pts + 1] = (S.hermite(e, s))
	end
	return pts
end
geom.polyline = polyline

--- Segments of a road centreline for offsetFromRoad: the polyline pts (starting at the road's
-- node) extended straight behind the node by `back` (kerbs of the junction model are extended
-- that way). Flat arrays of start x, y and direction x, y, squared length: kerbCut asks for the
-- offset dozens of times per road, so the segments are built once.
local function roadSegments(pts, back)
	local ax, ay, dx, dy, l2 = {}, {}, {}, {}, {}
	local function seg(a, b)
		local n = #ax + 1
		ax[n], ay[n], dx[n], dy[n] = a[1], a[2], b[1] - a[1], b[2] - a[2]
		l2[n] = dx[n] * dx[n] + dy[n] * dy[n]
	end
	seg(add(pts[1], scale(norm(sub(pts[1], pts[2])), back)), pts[1])
	for i = 1, #pts - 1 do seg(pts[i], pts[i + 1]) end
	return { ax = ax, ay = ay, dx = dx, dy = dy, l2 = l2 }
end

--- Signed offset of q from a road centreline (positive to the left, looking away from the node),
-- segs from roadSegments. Same arithmetic as S.distToSegment and S.cross, without allocations.
local mmax, mmin, msqrt = math.max, math.min, math.sqrt
local function offsetFromRoad(q, segs)
	local ax, ay, dx, dy, l2 = segs.ax, segs.ay, segs.dx, segs.dy, segs.l2
	local qx, qy = q[1], q[2]
	local best, sign = math.huge, 1
	for i = 1, #ax do
		local ex, ey = qx - ax[i], qy - ay[i]
		local s = 0
		if l2[i] > 1e-9 then s = mmax(0, mmin(1, (ex * dx[i] + ey * dy[i]) / l2[i])) end
		local rx, ry = qx - (ax[i] + dx[i] * s), qy - (ay[i] + dy[i] * s)
		local d = msqrt(rx * rx + ry * ry)
		if d < best then
			best = d
			sign = dx[i] * ey - dy[i] * ex >= 0 and 1 or -1
		end
	end
	return sign * best
end

--- Junction cut-back on a ring (ellipse a, b, centred on the origin, road half width hw): the arc
-- length along the centreline from parameter t0 (a node) towards t1 until the ring's kerb on the
-- side of a road leaving the node at p in direction d (half width w) leaves that road's kerb lines
-- (the strip of half width w around its axis, extended behind the node). This is where the two
-- kerbs meet: the kerb corner of the junction model (tests/square_roundabouts/checks.lua). Returns
-- math.huge if the kerb is still inside the strip at t1 (the junction eats the whole edge).
-- A curved road (splitter leg) passes its centreline points `pts` (from the node outwards): the
-- kerb then leaves the road's band around that curve instead of a straight strip.
function geom.kerbCut(a, b, hw, t0, t1, p, d, w, pts)
	local side = dot(d, S.ellipseNormal(a, b, t0)) >= 0 and 1 or -1
	local v = left(d)
	-- the road's kerb that faces the edge: on the side the edge leaves the node towards
	local facing = dot(S.ellipseDeriv(a, b, t0), v) * (t1 - t0) >= 0 and 1 or -1
	local segs = pts and roadSegments(pts, 3 * w)
	local function lateral(t)
		local k = add(S.ellipsePoint(a, b, t), scale(S.ellipseNormal(a, b, t), side * hw))
		if segs then return facing * offsetFromRoad(k, segs) end
		return facing * dot(sub(k, p), v)
	end
	local n = geom.KERB_SAMPLES
	local arc, prev = 0, S.ellipsePoint(a, b, t0)
	local prevT = t0
	for k = 1, n do
		local t = t0 + (t1 - t0) * k / n
		local q = S.ellipsePoint(a, b, t)
		if lateral(t) >= w then
			-- refine between prevT and t
			local lo, hi = prevT, t
			for _ = 1, 20 do
				local mid = (lo + hi) / 2
				if lateral(mid) >= w then hi = mid else lo = mid end
			end
			-- second result: where the corner lies along the road (negative: behind its node)
			local corner = add(S.ellipsePoint(a, b, hi), scale(S.ellipseNormal(a, b, hi), side * hw))
			return arc + dist(prev, S.ellipsePoint(a, b, hi)), dot(sub(corner, p), d)
		end
		arc = arc + dist(prev, q)
		prev, prevT = q, t
	end
	return math.huge, 0
end

--- Arc length of the ellipse between parameters t0 and t1.
function geom.arcLength(a, b, t0, t1)
	local n = geom.KERB_SAMPLES
	local total, prev = 0, S.ellipsePoint(a, b, t0)
	for k = 1, n do
		local q = S.ellipsePoint(a, b, t0 + (t1 - t0) * k / n)
		total = total + dist(prev, q)
		prev = q
	end
	return total
end

--- Smallest free length (arc minus the junction cut-backs at both ends) over the edges of a ring
-- with node parameters ts (ascending) and spokes[i] = {{p, d, w, pts?}} (roads leaving node i),
-- the farthest a kerb corner lies behind a road's node (a radial arm on an oval's flank meets
-- the ring at a slant), and that farthest for the straight roads that end at their node alone
-- (spokes without pts or `continued`: plain arms; splitter legs pass their curve as pts, and an
-- axis arm with the road through the centre straight opposite runs on through the node, which
-- the engine-fitted model does not count, tests/square_roundabouts/checks.lua checks.junctions).
function geom.ringFree(a, b, hw, ts, spokes)
	local worst, behind, behindStraight = math.huge, 0, 0
	local function corner(along, sp)
		behind = math.max(behind, -along)
		if not (sp.pts or sp.continued) then behindStraight = math.max(behindStraight, -along) end
	end
	for i = 1, #ts do
		local j = i % #ts + 1
		local t0, t1 = ts[i], (j == 1) and (ts[1] + TWO_PI) or ts[j]
		local cut0, cut1 = 0, 0
		for _, sp in ipairs(spokes[i] or {}) do
			local c, along = geom.kerbCut(a, b, hw, t0, t1, sp.p, sp.d, sp.w, sp.pts)
			cut0 = math.max(cut0, c)
			corner(along, sp)
		end
		for _, sp in ipairs(spokes[j] or {}) do
			local c, along = geom.kerbCut(a, b, hw, t1, t0, sp.p, sp.d, sp.w, sp.pts)
			cut1 = math.max(cut1, c)
			corner(along, sp)
		end
		worst = math.min(worst, geom.arcLength(a, b, t0, t1) - cut0 - cut1)
	end
	return worst, behind, behindStraight
end

--- Smallest delta > 0 with side * lateral(phi + side * delta) = target, where lateral is the offset
-- of the ellipse point in direction phi + side * delta from the arm axis (through p0 along u).
local function solveSide(a, b, phi, p0, v, side, target, scan)
	local function f(delta)
		local q = S.ellipsePoint(a, b, S.paramForAngle(a, b, phi + side * delta))
		return side * dot(sub(q, p0), v) - target
	end
	local lo, hi = 0, HALF_PI
	if f(hi) < 0 then
		-- not monotonic (a normal split axis on an oval's flank, geom.splitAxis): the first crossing
		if not scan then return nil end
		local found
		for k = 1, 90 do
			if f(k * HALF_PI / 90) >= 0 then found = k; break end
		end
		if not found then return nil end
		lo, hi = (found - 1) * HALF_PI / 90, found * HALF_PI / 90
	end
	for _ = 1, 60 do
		local mid = (lo + hi) / 2
		if f(mid) < 0 then lo = mid else hi = mid end
	end
	return hi
end

--- Ring plan at one radius: ellipse, anchors (the ring nodes the arms, legs and through road
-- join), all ring node parameters. Returns nil if it does not fit (unless force):
--   * every ring edge chord >= MIN_EDGE;
--   * splitter legs: both ring nodes exist and are neighbours on the ring;
--   * a leg meets the ring within LEG_MAX_TURN of the ring's normal, and so steeply that its
--     square end stays inside the ring road (pointed oval ends, 1-lane rings: the leg would
--     otherwise run along the ring, or its corner would reach the centre island), and it drives
--     with the circulation, not against it;
--   * where a leg meets the ring next to another arm's road, the chord between the two ring
--     nodes >= sum of their road half widths + LEG_CLEARANCE;
--   * a through road clears every ring node off its axis by the sum of its half width, the
--     widest road at that node and LEG_CLEARANCE (so it only touches its own two nodes' edges).
function geom.plan(spec, radius, arms, force)
	local lanes = spec.lanes
	local offset = geom.RING_OFFSET[lanes]
	local hw = geom.RING_HALF_WIDTH[lanes]
	local b = radius + offset
	local a = radius * (spec.ovalRatio or 1) + offset
	local sigma = spec.direction == geom.DIRECTION_CW and -1 or 1
	local sp = geom.splitParams(spec)
	local leg, spread = sp.leg, sp.spread

	local anchors = {}
	for i, arm in ipairs(arms) do
		-- splitter arms keep the radial axis (the split node and fork are tested that way); a plain
		-- arm leaves along the ring normal (geom.armDir)
		local u = arm.splitter and geom.splitAxis(spec, a, b, arm.phi) or geom.armDir(a, b, arm.phi)
		local v = left(u)
		local p0 = S.ellipsePoint(a, b, S.paramForAngle(a, b, arm.phi))
		local hwArm = geom.ARM_HALF_WIDTH[spec.armType]
		if arm.splitter then
			-- the legs fork from the neck when there is one (geom.splitParams)
			local hwFork = forkRoadHalfWidth(spec, sp)
			local target = leg.halfWidth + spread
			local dPlus = solveSide(a, b, arm.phi, p0, v, 1, target, spec.splitNormal)
			local dMinus = solveSide(a, b, arm.phi, p0, v, -1, target, spec.splitNormal)
			if not (dPlus and dMinus) then
				if not force then return nil end
				dPlus, dMinus = 0.3, 0.3
			end
			local plusPhi, minusPhi = arm.phi + dPlus, arm.phi - dMinus
			local entryPhi = sigma > 0 and plusPhi or minusPhi
			local exitPhi = sigma > 0 and minusPhi or plusPhi
			local tx, te = S.paramForAngle(a, b, exitPhi), S.paramForAngle(a, b, entryPhi)
			-- (as built below: both legs turn LEG_ENTRY from the ring normal at the arm towards sigma)
			local un = S.ellipseNormal(a, b, S.paramForAngle(a, b, arm.phi))
			local vn = left(un)
			local cg, sg = math.cos(geom.LEG_ENTRY), sigma * math.sin(geom.LEG_ENTRY)
			if not force then
				-- leg direction at the ring: the arm axis turned LEG_ENTRY towards the side of the node
				-- and the leg's square end (half width leg.halfWidth) stays inside the ring road band
				local cosMax = math.cos(math.min(geom.LEG_MAX_TURN, math.asin(math.min(1, hw / leg.halfWidth))))
				for k, t in ipairs({ tx, te }) do
					local travel = k == 1 and combine(un, cg, vn, sg) or combine(un, -cg, vn, sg)
					local outward = k == 1 and travel or scale(travel, -1)
					if dot(outward, S.ellipseNormal(a, b, t)) < cosMax then return nil end
					-- the leg must drive with the circulation, not against it
					local tau = scale(norm(S.ellipseDeriv(a, b, t)), sigma)
					if dot(travel, tau) <= 0.05 then return nil end
				end
			end
			-- outward directions of the legs at the ring (the exit drives out, the entry in)
			local exit, entry = geom.legEdges(spec, a, b, hw, arm.phi, S.ellipsePoint(a, b, tx), S.ellipsePoint(a, b, te), sigma)
			if not force then
				-- the split node's junction: the wide arm's kerb corner no more than BEHIND_PLAN
				-- behind it (see geom.legShape)
				local split = exit.p1
				for _, e in ipairs({ exit, entry }) do
					local pts = polyline(e, e == exit, 48)
					if geom.splitBehind(split, u, hwFork, pts, leg.halfWidth) > geom.BEHIND_PLAN then return nil end
				end
				-- a leg leaves the ring road's band within LEG_HUG of its ring node (on a tight oval
				-- end a wide fork could run it alongside the ring)
				for _, e in ipairs({ exit, entry }) do
					local fromEnd = e == entry
					local pts = polyline(e, fromEnd, 32)
					local run = 0
					for k = 2, #pts do
						run = run + dist(pts[k - 1], pts[k])
						if run > geom.LEG_HUG and S.distToEllipse(a, b, pts[k]) < hw + leg.halfWidth + 0.5 then return nil end
					end
				end
			end
			anchors[#anchors + 1] = { t = tx, arm = i, kind = "X", hw = leg.halfWidth, out = combine(un, cg, vn, sg), pts = polyline(exit, false, 16) }
			anchors[#anchors + 1] = { t = te, arm = i, kind = "E", hw = leg.halfWidth, out = combine(un, cg, vn, -sg), pts = polyline(entry, true, 16) }
		else
			anchors[#anchors + 1] = { t = S.paramForAngle(a, b, arm.phi), arm = i, kind = "P", hw = hwArm, out = u }
		end
	end

	local ts = {}
	for i, an in ipairs(anchors) do ts[i] = an.t end
	local ringTs, anchorAt = geom.ringParams(ts)

	local plan = { a = a, b = b, halfWidth = hw, sigma = sigma, leg = leg, anchors = anchors, ts = ringTs, anchorAt = anchorAt }
	if force then return plan end

	local function at(t) return S.ellipsePoint(a, b, t) end
	for i = 1, #ringTs do
		if dist(at(ringTs[i]), at(ringTs[i % #ringTs + 1])) < geom.MIN_EDGE - 1e-9 then return nil end
	end
	-- anchors in ring order
	local order = {}
	for i = 1, #ringTs do
		if anchorAt[i] then order[#order + 1] = anchors[anchorAt[i]] end
	end
	for i = 1, #order do
		local p, q = order[i], order[i % #order + 1]
		if #order > 1 and p.arm ~= q.arm and (p.kind ~= "P" or q.kind ~= "P") then
			if dist(at(p.t), at(q.t)) < p.hw + q.hw + geom.LEG_CLEARANCE then return nil end
		end
		if #order > 1 and p.arm ~= q.arm then
			-- neighbouring roads leaving the ring must not overlap where they start: the nearer
			-- start corner of each keeps LEG_CLEARANCE from the other's band (wide plain arms on a
			-- small ring did, Phase 1/2)
			for _, pair in ipairs({ { p, q }, { q, p } }) do
				local A, B = pair[1], pair[2]
				if dot(A.out, B.out) > 0 then
					local pa, pb = at(A.t), at(B.t)
					local n = left(A.out)
					if dot(sub(pb, pa), n) < 0 then n = scale(n, -1) end
					local m = left(B.out)
					if dot(sub(pa, pb), m) < 0 then m = scale(m, -1) end
					local corner = add(pb, scale(m, B.hw))
					if dot(sub(corner, pa), n) < A.hw + geom.LEG_CLEARANCE then return nil end
				end
			end
		end
		if p.kind ~= "P" then
			-- the two legs of an arm are neighbours on the ring (one of the two sides of p)
			local prev = order[(i - 2) % #order + 1]
			if q.arm ~= p.arm and prev.arm ~= p.arm then return nil end
		end
	end
	local axisArm
	for _, arm in ipairs(arms) do
		if arm.axis then axisArm = axisArm or arm end
	end
	-- junction room: every ring edge keeps JUNCTION_PLAN outside the junctions at its ends (wide
	-- arms and a through road cut far into a small ring)
	local spokes = {}
	for i = 1, #ringTs do
		local an = anchorAt[i] and anchors[anchorAt[i]]
		if an then
			local p = at(ringTs[i])
			spokes[i] = { { p = p, d = an.out, w = an.hw, pts = an.pts } }
			if an.kind == "P" and arms[an.arm].axis then
				spokes[i][2] = { p = p, d = scale(an.out, -1), w = geom.throughHalfWidth(spec), continued = true }
				spokes[i][1].continued = true
			end
		end
	end
	local free, behind, behindStraight = geom.ringFree(a, b, hw, ringTs, spokes)
	if free < geom.JUNCTION_PLAN or behind > geom.BEHIND_PLAN then return nil end
	if behindStraight > geom.ARM_BEHIND_PLAN and not geom.radiusSearched(spec) then return nil end
	if axisArm then
		local through = geom.throughHalfWidth(spec)
		local w = left(dir(axisArm.phi))
		for i = 1, #ringTs do
			local an = anchorAt[i] and anchors[anchorAt[i]]
			if not (an and arms[an.arm].axis) then
				-- an arm or leg starting at the node is as wide as its road
				local wide = math.max(hw, an and an.hw or 0)
				if math.abs(dot(at(ringTs[i]), w)) < through + wide + geom.LEG_CLEARANCE then return nil end
			end
		end
		-- between the nodes too (a flat oval side can run inside the through road's strip): the
		-- ring may enter the strip only within THROUGH_JUNCTION of the two axis nodes
		local ends = {}
		for i = 1, #ringTs do
			local an = anchorAt[i] and anchors[anchorAt[i]]
			if an and arms[an.arm].axis then ends[#ends + 1] = at(ringTs[i]) end
		end
		for k = 0, geom.THROUGH_SAMPLES - 1 do
			local p = at(2 * PI * k / geom.THROUGH_SAMPLES)
			if math.abs(dot(p, w)) < through + hw + geom.LEG_CLEARANCE then
				local near = false
				local junction = math.max(geom.THROUGH_JUNCTION, through + hw + 4)
				for _, q in ipairs(ends) do
					if dist(p, q) <= junction then near = true end
				end
				if not near then return nil end
			end
		end
	end
	return plan
end

--- Half width of the through road (its road, the arm road by default; for a tram line the wider of its stubs and tram_new).
function geom.throughHalfWidth(spec)
	-- tram line: the town tram stubs at the ring are wider than tram_new
	if spec.centre == geom.CENTRE_TRAM then
		return math.max(geom.TRAM_THROUGH.halfWidth, geom.ARM_HALF_WIDTH[geom.TRAM_STUB_ARM])
	end
	return geom.ARM_HALF_WIDTH[spec.throughType or spec.armType]
end

--- Effective radius: the chosen radius, or the smallest larger radius on the slider (then
-- GROW_RADII) at which the ring fits (geom.plan). Splitter legs, a through road and wide arms
-- need room. Returns the plan and the radius in metres.
-- Engine data first (geom.engineRadius, Phase 4b): where the probe found the radius the engine
-- accepts for this layout, the ring is built at exactly that radius, even if the offline model
-- rejects it (plan.engine; plan.offline tells what the model said): the engine is the judge, and
-- the layout is the one it accepted. An engine radius the engine did not see for exactly this
-- layout (copied from anticlockwise, a splitter floor taken over from another layout or shape)
-- is a floor: used if the offline model accepts it, else the growth starts above it. Without
-- engine data nothing changes.
function geom.choosePlan(spec, arms)
	local exact, verified, source = geom.engineRadius(spec)
	if exact then
		local plan = geom.plan(spec, exact, arms)
		local offline = plan ~= nil
		if plan or verified then
			if not plan then plan = geom.plan(spec, exact, arms, true) end
			plan.spec, plan.engine, plan.offline = spec, source, offline
			return plan, exact
		end
	end
	local function radii(sp)
		for i = sp.radiusIndex, #geom.RADII do
			local r = geom.RADII[i]
			if not exact or r > exact then
				local plan = geom.plan(sp, r, arms)
				if plan then return plan, r end
			end
		end
		for _, r in ipairs(geom.GROW_RADII) do
			if not exact or r > exact then
				local plan = geom.plan(sp, r, arms)
				if plan then return plan, r end
			end
		end
	end
	local plan, r = radii(spec)
	if plan then plan.spec, plan.floor = spec, exact; return plan, r end
	-- splitter legs that fit nowhere: open the fork and spread the legs step by step (the nearest
	-- working layout; mostly medium/large arms on small or long oval rings)
	if spec.splitter == geom.SPLITTER_ON then
		for bump = 1, 4 do
			local wider = {}
			for k, v in pairs(spec) do wider[k] = v end
			wider.forkBump = bump
			plan, r = radii(wider)
			if plan then plan.spec, plan.floor = wider, exact; return plan, r end
		end
	end
	-- splitter arms on a long oval's flank (2:1, large arms): a radial split runs its legs along the
	-- ring at every radius; split along the ring normal instead, like a plain arm (Phase 5f: the
	-- radial layout was forced at 60 m for 2:1, 4 lanes, Y / 5 arms, large arms), from the engine
	-- floor if there is one
	if spec.splitter == geom.SPLITTER_ON and spec.shape ~= geom.SHAPE_ROUND then
		local normal = {}
		for k, v in pairs(spec) do normal[k] = v end
		normal.splitNormal = true
		if exact then
			plan = geom.plan(normal, exact, arms)
			if plan then plan.spec, plan.floor = normal, exact; return plan, exact end
		end
		plan, r = radii(normal)
		if plan then plan.spec, plan.floor = normal, exact; return plan, r end
	end
	-- an engine floor the offline model rejects at every radius (a splitter rule taken over from
	-- round rings onto a long oval): the layout at the floor, for the engine to judge (probe
	-- search_radius_split); built.engine = "floor", built.offline = false
	if exact then
		plan = geom.plan(spec, exact, arms, true)
		plan.spec, plan.engine, plan.offline = spec, source, false
		return plan, exact
	end
	-- never reached for the shipped params (tested); keep a valid result anyway
	plan = geom.plan(spec, geom.RADII[#geom.RADII], arms, true)
	plan.spec, plan.forced = spec, true
	return plan, geom.RADII[#geom.RADII]
end

local function list(role, entry, halfWidth, edges)
	return { role = role, template = entry.template, tramTrackType = entry.tramTrackType, halfWidth = halfWidth, edges = edges }
end

--- Ring + arms + legs + through road + islands for a spec from readParams. Pure: same spec, same result.
-- Returns {
--   a, b,                  ring centreline semi-axes (x, y)
--   halfWidth, radius,     ring road half width; effective radius (>= the chosen one)
--   lists = {{role, template, tramTrackType?, halfWidth, edges, signalYes?, signalPref?}}
--          roles: "ring" (first), "arms", "legs", "through"; one list per template
--   ring = lists[1] plus nodes = {{pos, tag, t, arm?, kind?}}
--   arms = { template, edges }   all arm edges by arm number (a view across the arm lists)
--   legs = {{arm, entry, exit, split}}, through = edge | nil, axis = {i, j} | nil
--   island = nil | { kind, faces = {{outline, fill, stroke?}}, colliders = {{type, x, y, rot, hx, hy, hz}},
--                    models = {{id, x, y, rot}} }
-- }
--- Dev override `radius` (geom.readDev): the plan at exactly that radius, without growth or the
-- tuning floor. If the offline model rejects it, the forced plan is built anyway (the probe asks
-- the engine about it); plan.offline tells which.
function geom.devPlan(spec, arms, radius)
	local plan = geom.plan(spec, radius, arms)
	local offline = plan ~= nil
	if not plan then
		plan = geom.plan(spec, radius, arms, true)
		plan.forced = true
	end
	plan.spec, plan.offline = spec, offline
	return plan, radius
end

function geom.build(spec)
	local arms, axis = geom.armsFor(spec)
	local plan, radius
	if spec.dev and spec.dev.radius then
		plan, radius = geom.devPlan(spec, arms, spec.dev.radius)
	else
		plan, radius = geom.choosePlan(spec, arms)
	end
	spec = plan.spec -- may carry a wider splitter fork (forkBump)
	local sp = geom.splitParams(spec)
	local a, b, hw, sigma = plan.a, plan.b, plan.halfWidth, plan.sigma

	-- ring nodes (counter-clockwise by parameter)
	local nodes = {}
	local byArm = {}
	for i, t in ipairs(plan.ts) do
		local an = plan.anchorAt[i] and plan.anchors[plan.anchorAt[i]]
		nodes[i] = { pos = S.ellipsePoint(a, b, t), tag = "sqrb_ring_" .. i, t = t, arm = an and an.arm, kind = an and an.kind }
		if an then
			byArm[an.arm] = byArm[an.arm] or {}
			byArm[an.arm][an.kind] = nodes[i]
		end
	end
	local ringEdges = geom.ringEdges(a, b, nodes, spec.direction)

	-- arms, legs
	local hwArm = geom.ARM_HALF_WIDTH[spec.armType]
	local plainArms, tramArms, legEdges, legs, allArms = {}, {}, {}, {}, {}
	local plainNecks, tramNecks = {}, {}
	local signalYes, signalPref = {}, {}
	for i, arm in ipairs(arms) do
		local u = arm.splitter and geom.splitAxis(spec, a, b, arm.phi) or geom.armDir(a, b, arm.phi)
		local v = left(u)
		local p0 = S.ellipsePoint(a, b, S.paramForAngle(a, b, arm.phi))
		local edge, entryNode
		if arm.splitter then
			local X, E = byArm[i].X, byArm[i].E
			local splitTag = "sqrb_split_" .. i
			local exit, entry, split = geom.legEdges(spec, a, b, hw, arm.phi, X.pos, E.pos, sigma, X.tag, E.tag, splitTag)
			local armStart, armTag = split, splitTag
			if sp.neck > 0 then
				-- a narrower two-way piece between the split node and the arm (dev override / tuning)
				armStart, armTag = add(split, scale(u, sp.neck)), "sqrb_neck_" .. i
				local neck = S.straightEdge(split, armStart, splitTag, armTag)
				neck.arm = i
				if arm.tram then tramNecks[#tramNecks + 1] = neck else plainNecks[#plainNecks + 1] = neck end
			end
			edge = S.straightEdge(armStart, add(armStart, scale(u, geom.ARM_LENGTH)), armTag, nil)
			entry.leg, exit.leg, entry.arm, exit.arm = "entry", "exit", i, i
			legEdges[#legEdges + 1] = exit
			legEdges[#legEdges + 1] = entry
			legs[#legs + 1] = { arm = i, entry = entry, exit = exit, split = split }
			entryNode = E
		else
			local n = byArm[i].P
			edge = S.straightEdge(n.pos, add(n.pos, scale(u, hw + geom.ARM_LENGTH)), n.tag, nil)
			entryNode = n
		end
		edge.arm = i
		if arm.tram then tramArms[#tramArms + 1] = edge else plainArms[#plainArms + 1] = edge end
		allArms[#allArms + 1] = edge
		-- experimental signals: odd arms use the tealdef field, even arms the wiki field
		if spec.signals == geom.SIGNALS_ENTRIES then
			if i % 2 == 1 then signalYes[#signalYes + 1] = entryNode.tag else signalPref[#signalPref + 1] = entryNode.tag end
		end
	end

	-- A tram line through the centre crosses the ring straight, so the ring itself gets no tram:
	-- tram turns onto the tight one-way ring are rejected by the engine ("Construction not
	-- possible", "transition not valid ... Crossing"; in-game test 2026-10-07).
	local ringTram = spec.tram == geom.TRAM_ON
	local ringEntry = ringTram and geom.RING_TRAM[spec.lanes] or { template = geom.RING_TEMPLATES[spec.lanes] }
	local ring = list("ring", ringEntry, hw, ringEdges)
	ring.nodes = nodes
	if #signalYes > 0 then ring.signalYes = signalYes end
	if #signalPref > 0 then ring.signalPref = signalPref end

	local lists = { ring }
	if #plainArms > 0 then lists[#lists + 1] = list("arms", { template = geom.ARM_TEMPLATES[spec.armType] }, hwArm, plainArms) end
	if #tramArms > 0 then lists[#lists + 1] = list("arms", geom.ARM_TRAM[spec.armType], hwArm, tramArms) end
	if #legEdges > 0 then
		local leg = plan.leg
		lists[#lists + 1] = list("legs", leg, leg.halfWidth, legEdges)
	end
	if #plainNecks > 0 then
		lists[#lists + 1] = list("neck", { template = geom.ARM_TEMPLATES[sp.neckType] }, geom.ARM_HALF_WIDTH[sp.neckType], plainNecks)
	end
	if #tramNecks > 0 then
		lists[#lists + 1] = list("neck", geom.ARM_TRAM[sp.neckType], geom.ARM_HALF_WIDTH[sp.neckType], tramNecks)
	end

	local through, throughHalf
	if axis then
		local n1, n2 = byArm[axis[1]].P, byArm[axis[2]].P
		through = S.straightEdge(n1.pos, n2.pos, n1.tag, n2.tag)
		-- the through road's template (Phase 5c "Through road"; the arm road by default), tram variant
		-- with Tram tracks On as the arms
		local tt = spec.throughType or spec.armType
		local road = spec.tram == geom.TRAM_ON and geom.ARM_TRAM[tt] or { template = geom.ARM_TEMPLATES[tt] }
		throughHalf = geom.throughHalfWidth(spec)
		if spec.centre == geom.CENTRE_TRAM then
			-- tram_new must not join the ring node itself: a tram-only edge in the ring + tram arm
			-- junction crashes the engine (transition_util.cpp:128 CompCurveHandleDistance, angle NaN;
			-- in-game test 2026-10-07). Town tram road stubs join the ring like a road through,
			-- and the tram-only line runs between them, joined by plain straight nodes.
			local tramRoad = geom.ARM_TRAM[geom.TRAM_STUB_ARM]
			local hwStub = geom.ARM_HALF_WIDTH[geom.TRAM_STUB_ARM]
			local e = norm(sub(n2.pos, n1.pos))
			local len = S.dist(n1.pos, n2.pos)
			local stub = hw + (spec.dev and spec.dev.tramStub or geom.TRAM_STUB)
			if len >= 2 * stub + geom.TRAM_MIDDLE_MIN then
				local q1, q2 = add(n1.pos, scale(e, stub)), sub(n2.pos, scale(e, stub))
				lists[#lists + 1] = list("through", tramRoad, hwStub, {
					S.straightEdge(n1.pos, q1, n1.tag, "sqrb_tram_a"),
					S.straightEdge(q2, n2.pos, "sqrb_tram_b", n2.tag),
				})
				lists[#lists + 1] = list("through", geom.TRAM_THROUGH, geom.TRAM_THROUGH.halfWidth,
					{ S.straightEdge(q1, q2, "sqrb_tram_a", "sqrb_tram_b") })
			else
				-- too short for stubs and a tram-only middle: the tram arm road all the way
				lists[#lists + 1] = list("through", tramRoad, hwStub, { through })
			end
		else
			local tl = list("through", road, throughHalf, { through })
			lists[#lists + 1] = tl
			if spec.centre == geom.CENTRE_ROAD_LIGHTS then geom.throughSignals(ring, tl, n1.tag, n2.tag) end
		end
	end

	local built = {
		a = a,
		b = b,
		halfWidth = hw,
		radius = radius,
		mini = radius < geom.MINI_RADIUS_BELOW,
		lists = lists,
		ring = ring,
		arms = { template = geom.ARM_TEMPLATES[spec.armType], edges = allArms },
		legs = legs,
		through = through,
		axis = axis,
		spec = spec,
		forced = plan.forced,
		-- the radius comes from engine data (geom.engineRadius): "radius", "inferred", "splitter", "floor"
		engine = plan.engine,
		-- an engine floor the offline model rejected: the ring grew from above it
		floor = plan.floor,
		-- with the dev radius override or engine data: whether the offline model accepted that radius
		offline = plan.offline,
	}
	built.island = geom.islands(spec, built, throughHalf)
	return built
end

--- Road + traffic lights (Phase 5c, experimental like sqrb_signals; TESTING.md 7.4 / 11.6 / 13):
-- lights at the two ring nodes the through road crosses, asked for on both lists that meet there
-- (the ring's two entries of the node and the through road's end). As the Traffic lights param,
-- the two candidate fields are split so the in-game test shows which one the engine reads: the
-- first axis node via trafficLightYes, the second via trafficLightNodePreference. A node the
-- Traffic lights param already lists on the ring (in either field) is not added again.
function geom.throughSignals(ring, through, tagA, tagB)
	local listed = {}
	for _, t in ipairs(ring.signalYes or {}) do listed[t] = true end
	for _, t in ipairs(ring.signalPref or {}) do listed[t] = true end
	for k, tag in ipairs({ tagA, tagB }) do
		local field = k == 1 and "signalYes" or "signalPref"
		if not listed[tag] then
			ring[field] = ring[field] or {}
			ring[field][#ring[field] + 1] = tag
		end
		through[field] = { tag }
	end
end

-- islands

--- Island kind after the mini rule (mini rings get a flat island), or nil for none.
function geom.islandKind(kind, mini)
	if kind == nil or kind == geom.ISLAND_NONE then return nil end
	if mini and (kind == geom.ISLAND_TREES or kind == geom.ISLAND_FOUNTAIN) then
		return geom.ISLAND_PAVED
	end
	return kind
end

--- Ground face of an island kind: {outline, fill, stroke?}.
function geom.face(kind, outline)
	if kind == geom.ISLAND_GRASS or kind == geom.ISLAND_TREES then
		return { outline = outline, fill = geom.GTEX_GRASS }
	end
	return { outline = outline, fill = geom.GTEX_PAVING_FILL, stroke = geom.GTEX_PAVING_STROKE }
end

--- Inner offset (CCW outline) of the ellipse (a, b) by halfWidth + ISLAND_MARGIN, and the semi-axes
-- of the largest centred ellipse inside it (less 2 %), or nil if there is no room.
function geom.islandOutline(a, b, halfWidth, centre)
	centre = centre or { 0, 0, 0 }
	local d = halfWidth + geom.ISLAND_MARGIN
	local minCurvature = math.min(a, b) ^ 2 / math.max(a, b) -- smallest radius of curvature
	if d >= minCurvature then return nil end
	local ai, bi = a - d, b - d
	if bi < geom.ISLAND_MIN_RADIUS or ai < geom.ISLAND_MIN_RADIUS then return nil end

	local outline = {}
	for k = 0, geom.ISLAND_SEGMENTS - 1 do
		local t = TWO_PI * k / geom.ISLAND_SEGMENTS
		local p = add(S.ellipsePoint(a, b, t), scale(S.ellipseNormal(a, b, t), -d))
		outline[#outline + 1] = { p[1] + centre[1], p[2] + centre[2], 0 }
	end

	-- The offset of an ellipse is not an ellipse: shrink the (ai, bi) ellipse until it fits inside
	-- the outline polygon (checked at every vertex and chord midpoint), less a small gap.
	local k = 1
	for i, p in ipairs(outline) do
		local q = outline[i % #outline + 1]
		local px, py = p[1] - centre[1], p[2] - centre[2]
		local mx, my = (p[1] + q[1]) / 2 - centre[1], (p[2] + q[2]) / 2 - centre[2]
		k = math.min(k, math.sqrt((px / ai) ^ 2 + (py / bi) ^ 2), math.sqrt((mx / ai) ^ 2 + (my / bi) ^ 2))
	end
	k = k * 0.98
	return outline, ai, bi, k
end

--- Trees, bushes or a fountain for a centred elliptic island of semi-axes ai, bi (bi <= ai).
-- Returns {{id, x, y, rot}} relative to the island centre.
function geom.islandModels(kind, ai, bi, centreModel)
	local models = {}
	local function ringOf(id, frac, spacing, minCount)
		local ra, rb = ai * frac, bi * frac
		local perimeter = PI * (3 * (ra + rb) - math.sqrt((3 * ra + rb) * (ra + 3 * rb))) -- Ramanujan
		local n = math.floor(perimeter / spacing)
		if n < minCount then return end
		for k = 0, n - 1 do
			local t = TWO_PI * (k + 0.5) / n
			models[#models + 1] = { id = id, x = ra * math.cos(t), y = rb * math.sin(t), rot = t }
		end
	end
	if centreModel == nil then centreModel = true end
	if kind == geom.ISLAND_TREES then
		if centreModel and bi >= 4 then
			models[#models + 1] = { id = geom.MODEL_TREE, x = 0, y = 0, rot = 0 }
		end
		if centreModel and bi >= 12 then
			ringOf(geom.MODEL_TREE, 0.5, 11, 3)
		end
		if bi >= 5 then
			ringOf(geom.MODEL_BUSH, 0.82, 5, 4)
		end
	elseif kind == geom.ISLAND_FOUNTAIN then
		if centreModel and bi >= 5 then
			models[#models + 1] = { id = geom.MODEL_FOUNTAIN, x = 0, y = 0, rot = 0 }
		end
		if bi >= 8 then
			ringOf(geom.MODEL_BUSH, 0.82, 5, 4)
		end
	end
	return models
end

local function centreModelId(kind)
	if kind == geom.ISLAND_TREES then return geom.MODEL_TREE end
	if kind == geom.ISLAND_FOUNTAIN then return geom.MODEL_FOUNTAIN end
	return nil
end

--- Splitter triangle between the inner kerbs of an arm's two legs and the ring's outer kerb, or nil.
function geom.splitterIsland(leg, a, b, ringHalf, legHalf, sigma)
	local limit = ringHalf + geom.ISLAND_MARGIN + 0.5 -- 0.5 m for the sag of the base chord
	return geom.legTriangle(leg, legHalf, sigma, function(p)
		return (p[1] / a) ^ 2 + (p[2] / b) ^ 2 > 1 and S.distToEllipse(a, b, p) >= limit
	end)
end

--- Triangle between the inner kerbs (+ ISLAND_MARGIN) of a splitter's two legs ({entry, exit}),
-- from the first kerb points clear(p) accepts (clear of the road the legs join) to where the kerbs
-- meet near the split node, or nil. Shared by the roundabout and the channelized junction.
function geom.legTriangle(leg, legHalf, sigma, clear)
	local N = 40
	local off = legHalf + geom.ISLAND_MARGIN
	local function kerb(e, fromEnd)
		local pts = {}
		for k = 0, N do
			local s = fromEnd and (1 - k / N) or (k / N)
			local p, d = S.hermite(e, s)
			pts[#pts + 1] = add(p, scale(left(norm(d)), sigma * off))
		end
		-- drop the points on or inside the road the legs join
		local out = {}
		for _, p in ipairs(pts) do
			if #out > 0 or clear(p) then out[#out + 1] = { p[1], p[2], 0 } end
		end
		return out
	end
	local ke = kerb(leg.entry, true)   -- from the joined road towards the split node
	local kx = kerb(leg.exit, false)
	if #ke < 2 or #kx < 2 then return nil end
	local tip, i, j = S.polylineIntersection(ke, kx)
	if not tip then return nil end
	local poly = {}
	for k = 1, i do poly[#poly + 1] = ke[k] end
	poly[#poly + 1] = tip
	for k = j, 1, -1 do poly[#poly + 1] = kx[k] end
	poly = S.ccw(poly)
	if S.area(poly) < geom.ISLAND_MIN_AREA then return nil end
	return poly
end

--- All islands: the centre island (whole, or two halves beside a through road) and the splitter
-- triangles. Built only when the centre island param is not None.
function geom.islands(spec, built, throughHalf)
	local kind = geom.islandKind(spec.island, built.mini)
	if not kind then return nil end
	local faces, colliders, models = {}, {}, {}
	local hz = geom.COLLIDER_HEIGHT / 2

	local outline, ai, bi, k = geom.islandOutline(built.a, built.b, built.halfWidth)
	if outline and not built.axis then
		faces[#faces + 1] = geom.face(kind, outline)
		colliders[#colliders + 1] = { type = "CYLINDER", x = 0, y = 0, rot = 0, hx = ai * k, hy = bi * k, hz = hz }
		models = geom.islandModels(kind, ai, bi)
	elseif outline then
		-- two halves beside the through road, each with a box collider and its own centre model
		local e = norm(sub(built.through.p1, built.through.p0))
		local w = left(e)
		local c = throughHalf + geom.ISLAND_MARGIN
		local bushes = geom.islandModels(kind, ai, bi, false)
		local centreId = centreModelId(kind)
		for _, side in ipairs({ 1, -1 }) do
			local n = scale(w, side)
			local half = S.clipHalfPlane(outline, n, c)
			if #half >= 3 and S.area(S.ccw(half)) >= geom.ISLAND_MIN_AREA then
				half = S.ccw(half)
				faces[#faces + 1] = geom.face(kind, half)
				local box = S.boxFrom(half, scale(e, side), c)
				if box then
					colliders[#colliders + 1] = { type = "BOX", x = box.x, y = box.y, rot = box.rot, hx = box.hx, hy = box.hy, hz = hz }
					local r = centreId and geom.MODEL_RADIUS[centreId]
					if r and S.fits(box.x, box.y, r, half) then
						models[#models + 1] = { id = centreId, x = box.x, y = box.y, rot = 0 }
					end
				end
				for _, m in ipairs(bushes) do
					if S.fits(m.x, m.y, geom.MODEL_RADIUS[m.id], half) then models[#models + 1] = m end
				end
			end
		end
	end

	local sigma = spec.direction == geom.DIRECTION_CW and -1 or 1
	for _, leg in ipairs(built.legs) do
		local tri = geom.splitterIsland(leg, built.a, built.b, built.halfWidth, geom.splitParams(spec).leg.halfWidth, sigma)
		if tri then faces[#faces + 1] = geom.face(kind, tri) end
	end

	if #faces == 0 then return nil end
	return { kind = kind, faces = faces, colliders = colliders, models = models }
end

--- Left-hand traffic from a right-hand layout (Channelized Junction, Roundabout Interchange): every
-- edge of built.lists and the island mirrored in x (x -> -x). Each edge keeps its direction (a
-- one-way road still runs from its p0 to its p1, now on the other side), island outlines turn CCW
-- again, colliders and models mirror their rotation.
function geom.mirrorX(built)
	local m = S.mirrorX
	for _, l in ipairs(built.lists) do
		for _, e in ipairs(l.edges) do
			e.p0, e.t0, e.p1, e.t1 = m(e.p0), m(e.t0), m(e.p1), m(e.t1)
		end
	end
	if built.island then
		for _, f in ipairs(built.island.faces) do
			local o = {}
			for i, p in ipairs(f.outline) do o[i] = m(p) end
			f.outline = S.ccw(o)
		end
		for _, c in ipairs(built.island.colliders) do
			c.x, c.rot = -c.x, PI - c.rot
		end
		for _, md in ipairs(built.island.models or {}) do
			md.x, md.rot = -md.x, PI - md.rot
		end
	end
end

--- Node entries for an edgeList: {position, tangent, tag?} pairs, 2 per edge (basics.md "Edge Lists").
function geom.toEdgeEntries(edges)
	local out = {}
	for _, e in ipairs(edges) do
		out[#out + 1] = { { e.p0[1], e.p0[2], e.p0[3] }, { e.t0[1], e.t0[2], e.t0[3] }, e.tag0 }
		out[#out + 1] = { { e.p1[1], e.p1[2], e.p1[3] }, { e.t1[1], e.t1[2], e.t1[3] }, e.tag1 }
	end
	return out
end

--- Every node index (0-based, as street_util_serialized.freeAllNodes).
function geom.allNodes(entries)
	local out = {}
	for i = 1, #entries do out[i] = i - 1 end
	return out
end

--- 0-based indices of the entries carrying one of the tags (both ends of a merged node).
function geom.nodesWithTags(entries, tags)
	local want = {}
	for _, t in ipairs(tags or {}) do want[t] = true end
	local out = {}
	for i, entry in ipairs(entries) do
		if entry[3] and want[entry[3]] then out[#out + 1] = i - 1 end
	end
	return out
end

