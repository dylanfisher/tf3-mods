--- Normalises the construction params (1-based indices, any of them may be missing) into plain
-- numbers. keys = the param keys used in the .con.lua.
function geom.readParams(params, keys)
	params = params or {}
	local k = keys or geom.PARAM_KEYS
	local spec = {}
	spec.shape = index(params[k.shape], #geom.SHAPE_RATIOS, geom.SHAPE_ROUND)
	spec.ovalRatio = geom.SHAPE_RATIOS[spec.shape]
	spec.lanes = index(params[k.lanes], #geom.RING_TEMPLATES, 2)
	if params[geom.RADIUS_PRESET_KEY] ~= nil then
		spec.radiusIndex = geom.RADIUS_PRESETS[index(params[geom.RADIUS_PRESET_KEY], #geom.RADIUS_PRESETS, geom.DEFAULT_RADIUS_PRESET)]
	else
		spec.radiusIndex = index(params[k.radius], #geom.RADII, geom.DEFAULT_RADIUS)
	end
	spec.radius = geom.RADII[spec.radiusIndex]
	spec.mini = spec.radius < geom.MINI_RADIUS_BELOW
	spec.layout = index(params[k.arms], #geom.ARM_LAYOUTS, 3)
	spec.armType = index(params[k.armType], #geom.ARM_TEMPLATES, 1)
	spec.direction = index(params[k.direction], 2, geom.DIRECTION_CCW)
	spec.island = index(params[k.island], 5, geom.ISLAND_NONE)
	spec.splitter = index(params[k.splitter], 2, geom.SPLITTER_OFF)
	spec.centre = index(params[k.centre], 4, geom.CENTRE_NONE)
	-- through road template (arm road index); "Same as arms" follows the arm road
	spec.throughRoad = index(k.throughRoad and params[k.throughRoad], 1 + #geom.ARM_TEMPLATES, geom.THROUGH_SAME)
	spec.throughType = spec.throughRoad == geom.THROUGH_SAME and spec.armType or spec.throughRoad - 1
	spec.tram = index(params[k.tram], 2, geom.TRAM_OFF)
	spec.signals = index(params[k.signals], 2, geom.SIGNALS_OFF)
	spec.dev = geom.readDev(params)
	return spec
end

