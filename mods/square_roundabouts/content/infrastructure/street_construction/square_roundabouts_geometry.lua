--- Sorted ring node parameters: every anchor parameter plus the fewest extra nodes so that no gap
-- exceeds maxAngle. Returns ts (ascending, in [0, 2pi)) and armAt (ts index -> anchor number).
function geom.ringParams(armTs, maxAngle)
	maxAngle = maxAngle or geom.MAX_EDGE_ANGLE
	local anchors = {}
	for i, t in ipairs(armTs) do anchors[#anchors + 1] = { t = S.wrap(t), arm = i } end
	table.sort(anchors, function(x, y) return x.t < y.t end)
	if #anchors == 0 then anchors[1] = { t = 0 } end

	local ts, armAt = {}, {}
	for i, anchor in ipairs(anchors) do
		local nextT = (i < #anchors) and anchors[i + 1].t or (anchors[1].t + TWO_PI)
		local gap = nextT - anchor.t
		local n = math.max(1, math.ceil(gap / maxAngle - 1e-7))
		ts[#ts + 1] = anchor.t
		if anchor.arm then armAt[#ts] = anchor.arm end
		for k = 1, n - 1 do
			ts[#ts + 1] = anchor.t + gap * k / n
		end
	end
	return ts, armAt
end

--- Closed ring of Hermite edges through nodes ({pos, tag, t}, ascending ellipse parameters t) of
-- an ellipse with semi-axes (a, b); node positions may be offset (satellite rings). Runs
-- anticlockwise, or clockwise for DIRECTION_CW.
function geom.ringEdges(a, b, nodes, direction)
	local edges = {}
	for i = 1, #nodes do
		local n0 = nodes[i]
		local n1 = nodes[i % #nodes + 1]
		local t1 = (i == #nodes) and (n1.t + TWO_PI) or n1.t
		local s = geom.hermiteScale(t1 - n0.t)
		edges[i] = {
			p0 = n0.pos, t0 = scale(S.ellipseDeriv(a, b, n0.t), s),
			p1 = n1.pos, t1 = scale(S.ellipseDeriv(a, b, t1), s),
			tag0 = n0.tag, tag1 = n1.tag,
		}
	end
	if direction == geom.DIRECTION_CW then
		local rev = {}
		for i = #edges, 1, -1 do
			local e = edges[i]
			rev[#rev + 1] = { p0 = e.p1, t0 = scale(e.t1, -1), p1 = e.p0, t1 = scale(e.t0, -1), tag0 = e.tag1, tag1 = e.tag0 }
		end
		edges = rev
	end
	return edges
end

