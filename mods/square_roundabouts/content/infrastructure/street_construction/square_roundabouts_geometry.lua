--- Picks list[i], falling back to list[default] for a missing or out-of-range index (params may
-- hold foreign values: docs/wiki/modding/constructions/basics.md "Tip" under Parameters).
local function index(i, n, default)
	i = tonumber(i)
	if i == nil or i < 1 or i > n or i ~= math.floor(i) then return default end
	return i
end
geom.index = index

--- Cubic Hermite tangent length per unit radius for a circular arc of angle theta:
-- 4 * tan(theta / 4), i.e. three times the Bezier control distance (4 / 3) * tan(theta / 4).
-- For a quarter circle this is 4 * (sqrt(2) - 1), the vanilla value.
function geom.hermiteScale(theta)
	return 4 * math.tan(theta / 4)
end

