"""Write tlconfig.lua at the repo root so VS Code's Teal extension resolves the
game API and every mod in mods/. Mirrors <install>/vscode-template/tlconfig.lua.
The file holds absolute paths, so it is gitignored; rerun after adding mods.

Usage: uv run tools/setup_teal.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from hubconfig import MODS_DIR, ROOT, game_install  # noqa: E402


def main() -> None:
    install = game_install()
    template = install / "vscode-template"
    dirs = [install / "api/tealdef", install / "base/tealdef", template]
    requires = ['require "api_def"', 'require "content_def"']
    for mod in sorted(p for p in MODS_DIR.iterdir() if p.is_dir()):
        tealdef = mod / "tealdef"
        mod_def = tealdef / f"{mod.name}_def.d.tl"
        if mod_def.is_file():
            # Official layout (e.g. urbangames_campaign_mission_08/tealdef/<modId>_def.d.tl).
            dirs.append(tealdef)
            requires.append(f'require "{mod.name}_def"')
        elif any(mod.rglob("*.d.tl")):
            dirs.append(mod)
    # global_env_def must be a module on include_dir; generate one that also loads the mods' _def files.
    env_dir = ROOT / ".cache" / "teal"
    env_dir.mkdir(parents=True, exist_ok=True)
    (env_dir / "hub_all_def.d.tl").write_text(
        "-- Generated by tools/setup_teal.py (like vscode-template/all_def.tl, plus each mod's tealdef).\n"
        + "\n".join(requires) + "\n"
    )
    dirs.append(env_dir)
    entries = "\n".join(f'\t\t"{d.as_posix()}",' for d in dirs)
    (ROOT / "tlconfig.lua").write_text(
        "-- Generated by tools/setup_teal.py; rerun `make teal` after adding mods with .d.tl files.\n"
        f"return {{\n\tinclude_dir = {{\n{entries}\n\t}},\n\tglobal_env_def = \"hub_all_def\"\n}}\n"
    )
    print(f"Wrote {ROOT / 'tlconfig.lua'} ({len(dirs)} include dirs)")


if __name__ == "__main__":
    main()
