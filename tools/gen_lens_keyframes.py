"""Write Photo Mode's Lens cutscene keyframe files (round 16b).

Runs mods/square_photo_mode/content/photo_mode/pm_lensdef.lua (pure Lua: the single source of the lenses,
sizes, elevations, headings and the keys' math) and writes one keyframe file per entry of its
`L.allFiles()`:

  mods/square_photo_mode/content/mission/keyframes/en/sqpm_lens_<lens>_<size>_<elev>_<heading>.lua  (holds)
  mods/square_photo_mode/content/mission/keyframes/en/sqpm_lensorbit_<lens>_<size>_<elev>.lua         (orbits)

in the campaign's keyframe format (`function data() return { camera = {...}, ... } end`), every key attached
to the placeholder entity L.ANCHOR. Only the `en/` copy: `playCutscene(path, true)` loaded the `en/` file in
every probe and Photo Mode session (the campaign has only en/ and de/ folders, so other languages fall back to
en). Plain literals, no code: the keyframe state has no api and nothing to compute.

Usage:
  uv run tools/gen_lens_keyframes.py           write the files (and remove stale sqpm_lens* files)
  uv run tools/gen_lens_keyframes.py --check   exit 1 when a file is missing, differs or is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from lupa import LuaRuntime

ROOT = Path(__file__).resolve().parent.parent
DEF = ROOT / "mods/square_photo_mode/content/photo_mode/pm_lensdef.lua"
OUT = ROOT / "mods/square_photo_mode/content/mission/keyframes/en"
PREFIXES = ("sqpm_lens_", "sqpm_lensorbit_")

HEADER = (
    "-- GENERATED by tools/gen_lens_keyframes.py from content/photo_mode/pm_lensdef.lua: do not edit.\n"
    "-- Photo Mode round 16b, the Lens ({what}): {mm} mm (fovY {fov:.4f}), eye {d:.0f} m from the subject,\n"
    "-- {elev} degrees above it{head}. Keys attached to placeholder {anchor} (pm_lens maps it to the subject).\n"
)


def num(v: float) -> str:
    """A literal with 6 decimals; never "-0" (a mirrored zero: written as 0)."""
    r = round(float(v), 6)
    if r == 0:
        return "0"
    if r.is_integer() and abs(r) < 1e15:
        return str(int(r))
    return repr(r)


def key_text(k) -> str:
    a = k["attachment"]
    p = k["position"]
    return (
        "\t\t{\n"
        f"\t\t\tangle = {num(k['angle'])},\n"
        f"\t\t\tattachment = {{ entity = {int(a['entity'])}, group = {int(a['group'])}, lockPitch = "
        f"{str(bool(a['lockPitch'])).lower()}, lockRoll = {str(bool(a['lockRoll'])).lower()}, lockYaw = "
        f"{str(bool(a['lockYaw'])).lower()} }},\n"
        f"\t\t\tfovY = {num(k['fovY'])},\n"
        f"\t\t\tpitch = {num(k['pitch'])},\n"
        f"\t\t\tposition = {{ {num(p[1])}, {num(p[2])}, {num(p[3])} }},\n"
        f"\t\t\troll = {num(k['roll'])},\n"
        f"\t\t\tspeed = {num(k['speed'])},\n"
        f"\t\t\ttime = {num(k['time'])},\n"
        "\t\t},\n"
    )


def build() -> dict[str, str]:
    lua = LuaRuntime(unpack_returned_tuples=True)
    L = lua.execute(DEF.read_text(encoding="utf-8"))
    files = {}
    names = {lens["key"]: (lens["mm"], i) for i, lens in L.LENSES.items()}
    for __, f in L.allFiles().items():
        name = f["name"]
        keys = [f["keys"][i] for i in range(1, len(f["keys"]) + 1)]
        parts = name.split("_")
        orbit = name.startswith("sqpm_lensorbit_")
        lens_key = parts[2]
        mm, li = names[lens_key]
        s, e = int(parts[3]), int(parts[4])
        d = L.distance(li, s)
        head = "" if orbit else f", heading {int(parts[5])} ({num(round(L.heading(int(parts[5])) * 180 / 3.141592653589793))} deg)"
        text = HEADER.format(what="orbit" if orbit else "hold", mm=mm, fov=L.fovY(li), d=d,
                             elev=L.ELEVS[e], head=head, anchor=int(L.ANCHOR))
        text += "\nfunction data()\n\treturn {\n\t\tcamera = {\n"
        text += "".join(key_text(k).replace("\t\t", "\t\t\t") for k in keys)
        text += ("\t\t},\n\t\tenvironmentParams = {},\n\t\tfades = {},\n\t\tmusic = \"\",\n\t\tportraits = {},\n"
                 "\t\tsubtitles = {},\n\t\tvoiceOvers = {},\n\t}\nend\n\nreturn data\n")
        files[name + ".lua"] = text
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only compare; exit 1 on a difference")
    args = ap.parse_args()
    files = build()
    OUT.mkdir(parents=True, exist_ok=True)
    existing = {p.name for p in OUT.iterdir() if p.name.startswith(PREFIXES)}
    stale = sorted(existing - set(files))
    differ = [n for n, t in files.items() if not (OUT / n).exists() or (OUT / n).read_text(encoding="utf-8") != t]
    if args.check:
        for n in differ:
            print(f"differs or missing: {n}")
        for n in stale:
            print(f"stale: {n}")
        print(f"{len(files)} lens keyframe files: {len(differ)} differ / missing, {len(stale)} stale")
        return 1 if differ or stale else 0
    for n in differ:
        (OUT / n).write_text(files[n], encoding="utf-8")
    for n in stale:
        (OUT / n).unlink()
    size = sum(len(t.encode()) for t in files.values())
    print(f"{len(files)} lens keyframe files ({size / 1024:.0f} KB): {len(differ)} written, {len(stale)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
