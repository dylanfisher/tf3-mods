def towns_lua(key: str, towns: list[dict]) -> str:
    out = [HEADER.format(key=key), "-- From data/states/" + key + "/towns.tsv: n = name, t = tags, p = population.\n", "return {\n"]
    for t in towns:
        tags = ", ".join(lua_str(x) for x in t["t"])
        out.append(f"\t{{ n = {lua_str(t['n'])}, t = {{ {tags} }}, p = {t['p']} }},\n")
    out.append("}\n")
    return "".join(out)


@functools.cache
def i18n_table() -> dict:
    data = json.loads((TEMPLATES / "i18n.json").read_text(encoding="utf-8"))
    return {lang: data[lang] for lang in LANGS if lang in data}


def i18n_render(state: dict, mod_json: dict) -> tuple[str, dict, list[str]]:
    """strings.json text, modinfo "localization" and lint errors. Keys are the English texts (tools/i18n.py):
    the set name (the only `_()` in the generated code, in the .names.lua) first, then the params' name / tooltip /
    values, i.e. tools/i18n.py's extraction order. "en" needs no block (no id keys)."""
    table = i18n_table()
    errors: list[str] = []
    name = state["name"]
    fill = lambda tmpl: tmpl.replace("{state}", name)  # noqa: E731
    for fld, want in (("modName", state["modName"]), ("setName", state["setName"]), ("summary", state["summary"])):
        if fill(table["en"][fld]) != want:
            errors.append(f"{state['key']}: {fld} {want!r} doesn't match templates/state_names/i18n.json "
                          f"{table['en'][fld]!r}, so it has no translations")
    keys = [state["setName"]]
    if state.get("emitRegionalSets"):  # their names need entries in i18n.json "strings" (reported below)
        keys += [rs["name"] for rs in state.get("regionalSets") or []]
    for param in mod_json["params"]:
        for text in [param["name"], param["tooltip"], *param["values"]]:
            if text not in keys:
                keys.append(text)
    out: dict[str, dict[str, str]] = {}
    loc: dict[str, dict[str, str]] = {}
    for lang in LANGS[1:]:
        block = table.get(lang)
        if block is None:
            errors.append(f"i18n.json: no {lang} block")
            continue
        strings = dict(block.get("strings") or {}, **{state["setName"]: fill(block["setName"])})
        missing = [k for k in keys if not strings.get(k)]
        if missing:
            errors.append(f"i18n.json: {lang} lacks {missing}")
        out[lang] = {k: strings[k] for k in keys if strings.get(k)}
        loc[lang] = {"name": fill(block["modName"]), "summary": fill(block["summary"])}
        for fld, limit in (("name", MAX_NAME), ("summary", MAX_SUMMARY)):
            if len(loc[lang][fld]) > limit:
                errors.append(f"{state['key']}: {lang} modinfo {fld} is {len(loc[lang][fld])} chars (max {limit})")
    return json.dumps(out, indent=4, ensure_ascii=False) + "\n", loc, errors


def changelog_html(state: dict) -> str:
    parts = []
    for entry in sorted(state.get("changelog") or [], key=lambda e: -int(e["rev"])):
        date = str(entry.get("date") or "")
        head = f"Revision {entry['rev']}" + (f" ({date})" if date else "")
        items = "\n".join(f"<li>{html.escape(i, quote=False)}</li>" for i in entry.get("items") or [])
        parts.append(f"<h4>{head}</h4>\n<ul>\n{items}\n</ul>")
    return "\n".join(parts)


def flag_credit(key: str) -> str:
    """Flag credit for the description, from branding/flags/SOURCES.json (tools/fetch_flags.py)."""
    try:
        flags = json.loads((ROOT / "branding" / "flags" / "SOURCES.json").read_text(encoding="utf-8"))["flags"]
        e = next(f for f in flags if f["key"] == key)
        return f"Wikimedia Commons ({e.get('license', 'see file page').lower()}, {e.get('author', 'unknown author')})"
    except (OSError, KeyError, StopIteration, ValueError):
        return "Wikimedia Commons"


def join_and(items: list[str]) -> str:
    items = [i for i in items if i]
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def count_of(n: int, plural: str) -> str:
    """count_of(1, "ferry terminals") -> "1 ferry terminal"."""
    if n == 1 and plural.endswith("s"):
        plural = plural[:-1]
    return f"{n} {plural}"


def cities_of(n: int) -> str:
    return f"{n} {'city' if n == 1 else 'cities'}"


def climate_sentence(state: dict) -> str:
    """ "Temperate maps: mostly western Washington, plus the coast. ..." from climates + regionLabels; "" without
    climates. Only positive weights count (weight 0 is a top-up); a missing base climate uses the whole state."""
    climates = state.get("climates") or {}
    labels = state.get("regionLabels") or {}
    parts = []
    for climate in CLIMATES:
        weights = {t: w for t, w in (climates.get(climate) or {}).items() if isinstance(w, (int, float)) and w > 0}
        if not weights:
            continue
        top_w = max(weights.values())
        order = sorted(weights, key=lambda t: (-weights[t], t))
        top = [labels.get(t, t) for t in order if weights[t] == top_w]
        rest = [labels.get(t, t) for t in order if weights[t] != top_w]
        where = join_and(top) if not rest else f"mostly {join_and(top)}, plus {join_and(rest)}"
        parts.append(f"{climate.capitalize()} maps: {where}.")
    if not parts:
        return ""
    missing = [c for c in CLIMATES if not any(isinstance(w, (int, float)) and w > 0 for w in (climates.get(c) or {}).values())]
    tail = (f"{join_and(missing).capitalize()} maps and climates from other mods use the whole state." if missing
            else "Climates from other mods use the whole state.")
    return " ".join(["a new game picks its towns by the map's climate."] + parts + [tail])


def description(state: dict, towns: list[dict], cities: dict, streets: list) -> str:
    # Every count below comes from the data, so the text stays right when the lists change. Sentences about a kind
    # of name with no data (no harbours, no neighbourhoods) are left out. The climate wording relies on the runFn
    # climate route (Probe 3, docs/findings.md); never claim big cities get the big towns (sn_logic.BIG_FIRST).
    pop = {t["n"]: t["p"] for t in towns}
    by_pop = lambda cs: sorted(cs, key=lambda c: -pop.get(c, 0))  # noqa: E731
    having = lambda kind: by_pop(c for c, e in cities.items() if e.get(kind))  # noqa: E731
    street_cities = having("streets")
    uniq = lambda kind: {n for e in cities.values() for n in (e.get(kind) or [])}  # noqa: E731
    station_cities = by_pop(c for c, e in cities.items() if e.get("rail") or e.get("airport") or e.get("harbor"))
    biggest = sorted(towns, key=lambda t: -t["p"])
    ex = state.get("examples") or {}
    harbor_word = state.get("harborWord") or "harbours"
    # (kind, words in "new ... get real names", count words)
    station_kinds = [(k, w, c) for k, w, c in (("rail", "train stations", "rail stations"), ("airport", "airports", "airports"),
                                                ("harbor", harbor_word, harbor_word)) if uniq(k)]
    esc = lambda v: html.escape(v, quote=False)  # noqa: E731
    # introTowns (state.lua, optional): the two towns in "N real towns from A to B"; default the two biggest
    # (Hawaii: Honolulu to Hilo, since the second-biggest CDP is the Honolulu suburb East Honolulu).
    pair = state.get("introTowns") or [t["n"] for t in biggest[:2]]
    if any(n not in pop for n in pair):
        raise SystemExit(f"state.lua introTowns: not in towns.tsv: {[n for n in pair if n not in pop]}")
    intro = [f"{len(towns)} real towns from {' to '.join(pair)}"]
    if street_cities:
        intro.append("real streets for your bus stops")
    if station_kinds:
        intro.append("real names for " + join_and([w for _, w, _ in station_kinds]))
    station_li = ""
    if station_kinds:
        like = f", like {ex['stations']}" if ex.get("stations") else ""
        counts = ", ".join(count_of(len(uniq(k)), c) for k, _, c in station_kinds)
        station_li = (f"\n<li><strong>Real station names</strong>: new {esc(join_and([w for _, w, _ in station_kinds]))} in "
                      f"{cities_of(len(station_cities))} get real names{esc(like)} ({esc(counts)}).</li>")
    hood_cities = having("neighborhoods")
    hood_li = ""
    if hood_cities:
        hood_li = (f"\n<li><strong>Neighbourhood names</strong>: new bus and tram stations in {cities_of(len(hood_cities))} are "
                   f"named after real neighbourhoods ({len(uniq('neighborhoods'))} in all).</li>")
    street_li = ""
    if street_cities:
        stops = f", like {ex['stops']}" if ex.get("stops") else ""
        street_li = (f"\n<li><strong>Real street names</strong>: new Road Stops in {cities_of(len(street_cities))} "
                     f"({esc(', '.join(street_cities[:3]))}, …) are named "
                     f"after their real streets{esc(stops)}: "
                     f"{sum(len(cities[c]['streets']) for c in street_cities)} streets in all, never twice in the same town.</li>")
    climate = climate_sentence(state)
    climate_li = f"\n<li><strong>Towns that suit your map</strong>: {esc(climate)}</li>" if climate else ""
    flavour = state.get("streetFlavour")
    text = (TEMPLATES / "description.html.tmpl").read_text(encoding="utf-8")
    values = {
        "STATE_NAME": state["name"],
        # "a Washington city" / "an Arizona city" (every US state name starting with a vowel takes "an").
        "A_STATE_NAME": ("an " if state["name"][:1] in "AEIOU" else "a ") + state["name"],
        "SET_NAME": state["setName"],
        "INTRO": ", ".join(intro[:-1]) + (", and " if len(intro) > 1 else "") + intro[-1],
        "TOWN_COUNT": str(len(towns)),
        "TOWN_FLAVOUR": state.get("townFlavour") or "small towns",
        "BIGGEST_TOWN": biggest[0]["n"],
        "GENERIC_STREET_COUNT": str(len(streets)),
        "STREET_FLAVOUR": f" ({flavour})" if flavour else "",
        "FLAG_CREDIT": flag_credit(state["key"]),
    }
    raw = {
        "CLIMATE_LI": climate_li,
        "STREET_LI": street_li,
        "STATION_LI": station_li,
        "NEIGHBORHOOD_LI": hood_li,
        "CHANGELOG": changelog_html(state),
        "EXTRA_NOTES": "".join(f"\n<li>{esc(n)}</li>" for n in state.get("notes") or []),
    }
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", esc(v))
    for k, v in raw.items():
        text = text.replace("{{" + k + "}}", v)
    left = re.findall(r"\{\{[A-Z_]+\}\}", text)
    assert not left, f"description.html.tmpl: unknown placeholders {left}"
    return text


def contested_map(key: str) -> dict[str, str]:
    """Normalized city names of this state's cities.lua (keys and aliases) that another state's cities.lua also
    has -> modId of the bigger city (population from each state's towns.tsv; ties go to the lower modId)."""
    mod_id = f"square_names_{key}"
    out = {}
    for n, cs in all_claims().items():
        mods = {m for _, m in cs}
        if mod_id in mods and len(mods) > 1:
            out[n] = sorted(cs, key=lambda c: (-c[0], c[1]))[0][1]
    return dict(sorted(out.items()))


@functools.cache
def all_claims() -> dict[str, list[tuple[int, str]]]:
    """Normalized city name -> [(population, modId)] over every state's cities.lua."""
    claims: dict[str, list[tuple[int, str]]] = {}
    for d in sorted(DATA_DIR.iterdir()):
        if not ((d / "state.lua").exists() and (d / "cities.lua").exists() and (d / "towns.tsv").exists()):
            continue
        state = load_lua(d / "state.lua")
        fold = to_ascii if isinstance(state, dict) and state.get("asciiFallback") else (lambda x: x)
        pops = {normalize(fold(t["n"])): t["p"] for t in read_towns(d / "towns.tsv")}
        cities = load_lua(d / "cities.lua")
        if not isinstance(cities, dict):
            continue
        for city, entry in cities.items():
            names = {normalize(fold(n)) for n in [city] + list((entry or {}).get("aliases") or [])}
            p = max((pops.get(n, 0) for n in names), default=0)
            for n in names:
                claims.setdefault(n, []).append((p, f"square_names_{d.name}"))
    return claims


def contested_lua(key: str, contested: dict[str, str]) -> str:
    body = "".join(f"\t[{lua_str(n)}] = {lua_str(m)},\n" for n, m in contested.items())
    return (HEADER.format(key=key) + "-- City names shared with other states of the series (G9): normalized cities.lua key or alias ->\n"
            "-- modId of the bigger city. rename.script.lua leaves a lost city to the winner while the winner is active,\n"
            "-- unless the game uses this mod's own name set. Regenerate every state when any cities.lua changes.\n"
            "return {\n" + body + "}\n")


def render(key: str) -> tuple[str, dict[Path, str], list[str]]:
    src = DATA_DIR / key
    state = load_lua(src / "state.lua")
    assert isinstance(state, dict)
    # asciiFallback: every shipped name (towns, streets, cities, stations, examples) is transliterated; the data
    # files keep the Census/official spelling. The Lua sources are transliterated as text, so they run unchanged.
    fold = to_ascii if state.get("asciiFallback") else (lambda x: x)
    sources = {name: fold((src / name).read_text(encoding="utf-8")) for name in ("streets.lua", "cities.lua", "state.lua")}
    towns = [{**t, "n": fold(t["n"])} for t in read_towns(src / "towns.tsv")]
    state = load_lua_text(sources["state.lua"])
    streets = load_lua_text(sources["streets.lua"])
    cities = load_lua_text(sources["cities.lua"])
    assert isinstance(state, dict) and isinstance(cities, dict) and isinstance(streets, list)
    errors = lint(key, state, towns, streets, cities)
    if state.get("key") != key:
        errors.append(f"{key}: state.lua key is {state.get('key')!r}")
    mod_id = f"square_names_{key}"
    mod = MODS_DIR / mod_id
    content = mod / "content"
    pkg = content / mod_id
    header = HEADER.format(key=key)
    files: dict[Path, str] = {}

    mod_json = {
        "modId": mod_id,
        "revision": int(state["revision"]),
        "severityAdd": "None",
        "severityRemove": "Critical",
        "visible": True,
        "cosmetic": True,
        "runScript": {"fileName": f"{mod_id}::/{mod_id}/mod.script@runFn"},
        "params": [
            {
                "key": "streetNames",
                "name": "Real street names",
                "tooltip": "New Road Stops in known cities get real street names.",
                "uiType": "ComboBox",
                "values": ["On", "Off"],
                "numbers": [1.0, 0.0],
                "defaultIndex": 0,
            },
            {
                "key": "stationNames",
                "name": "Real station names",
                "tooltip": "New train stations, bus/tram stations, airports and harbours in known cities get real names.",
                "uiType": "ComboBox",
                "values": ["On", "Off"],
                "numbers": [1.0, 0.0],
                "defaultIndex": 0,
            },
            # SQPERF level 3 gate (plans/sqperf/README.md), copied from square_problem_radar's mod.json. Always
            # last: saves store params by key, and the two above keep their order and indices.
            {
                "key": "sqperf_log",
                "name": "Debug: performance log",
                "tooltip": "Off: normal play. On: every 30 s, this mod writes how long its name lists and station "
                           "renaming took to the game's log file (stdout.txt, lines starting with [SQPERF]), plus one "
                           "line per renamed stop or station. Only for tracking down slowdowns; leave it Off "
                           "otherwise. Slow calls are always logged briefly, whatever this setting.",
                "uiType": "Button",
                "values": ["Off", "On"],
                "defaultIndex": 0,
            },
        ],
    }
    files[mod / "mod.json"] = json.dumps(mod_json, indent=4, ensure_ascii=False) + "\n"
    strings_json, localization, i18n_errors = i18n_render(state, mod_json)
    errors += i18n_errors
    files[mod / "strings.json"] = strings_json
    modinfo = {
        "name": state["modName"],
        "summary": state["summary"],
        "description": f"{state['summary']} Adds the name set \"{state['setName']}\" and renames new stops and "
                       f"stations in known {state['name']} cities.",
        "localization": localization,
        "authors": [{"name": "square", "role": "CREATOR"}],
        "tags": ["Script Mod", "Misc"],
        "dependencies": [],
        "url": "",
    }
    files[mod / "_metadata" / "modinfo.json"] = json.dumps(modinfo, indent=4, ensure_ascii=False) + "\n"
    files[mod / "_metadata" / "description.html"] = description(state, towns, cities, streets)

    files[content / "names" / mod_id / f"{key}.names.lua"] = names_lua(mod_id, key, state["setName"])
    if state.get("emitRegionalSets"):
        for rs in state.get("regionalSets") or []:
            tags = ", ".join(lua_str(t) for t in rs["tags"])
            extra = f" tags = {{ {tags} }}, setId = {lua_str(rs['id'])} "
            files[content / "names" / mod_id / f"{key}_{rs['id']}.names.lua"] = names_lua(mod_id, key, rs["name"], extra)

    for name in ("mod.script.lua", "names.script.lua", "rename.script.lua", "rename.gs.lua", "sn_logic.lua", "sn_shared.lua"):
        files[pkg / name] = header + subst((TEMPLATES / "content" / name).read_text(encoding="utf-8"), mod_id, key)
    files[pkg / "data" / "towns.lua"] = towns_lua(key, towns)
    for name in ("streets.lua", "cities.lua", "state.lua"):
        files[pkg / "data" / name] = header + sources[name]
    files[pkg / "data" / "contested.lua"] = contested_lua(key, contested_map(key))
    # Presence marker every hub mod ships (tools/new_mod.py); rendered here so a regeneration keeps it.
    files[content / f"{mod_id}_presence.lua"] = PRESENCE_STUB.format(mod_id=mod_id)
    # SQPERF copy: the same files and bytes tools/sqperf_sync.py would write (no tealdef/ here, so only the two
    # content/sqperf/ files). Rendered here because everything under content/ not rendered counts as stale.
    for path, data in sqperf_sync.expected(mod).items():
        files[path] = data.decode("utf-8")
    for test in sorted((TEMPLATES / "tests").glob("test_*.lua")):
        files[TESTS_DIR / mod_id / test.name] = header + subst(test.read_text(encoding="utf-8"), mod_id, key)
    return mod_id, files, errors


def managed_existing(mod_id: str) -> set[Path]:
    """Files under the generated dirs (anything there not rendered is stale)."""
    out: set[Path] = set()
    for d in (MODS_DIR / mod_id / "content", TESTS_DIR / mod_id):
        if d.is_dir():
            out.update(p for p in d.rglob("*") if p.is_file() and p.name != ".DS_Store")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("states", nargs="*", help="state keys (data/states/<key>)")
    ap.add_argument("--all", action="store_true", help="every state in data/states/")
    ap.add_argument("--check", action="store_true", help="don't write; exit 1 if anything is stale or the lint fails")
    args = ap.parse_args()
    keys = sorted(p.name for p in DATA_DIR.iterdir() if (p / "state.lua").exists()) if args.all else args.states
    if not keys:
        ap.error("name a state (e.g. us_washington) or pass --all")
    failed = False
    for key in keys:
        mod_id, files, errors = render(key)
        for e in errors:
            print(f"lint: {e}")
        failed |= bool(errors)
        # Compared and written as bytes: the SQPERF copies must match tools/sqperf/ byte for byte.
        stale = [p for p, text in files.items() if not p.exists() or p.read_bytes() != text.encode("utf-8")]
        extra = sorted(managed_existing(mod_id) - set(files))
        rel = lambda p: p.relative_to(ROOT).as_posix()  # noqa: E731
        if args.check:
            for p in stale:
                print(f"stale: {rel(p)}")
            for p in extra:
                print(f"not generated: {rel(p)}")
            failed |= bool(stale or extra)
            print(f"{mod_id}: {'OK' if not (stale or extra or errors) else 'FAIL'}")
            continue
        if errors:
            print(f"{mod_id}: lint failed, nothing written")
            continue
        for p in stale:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(files[p].encode("utf-8"))
        for p in extra:
            p.unlink()
        print(f"{mod_id}: {len(files)} files, {len(stale)} written, {len(extra)} removed")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
