# Letters NFKD can't take apart, and quote marks: ASCII forms for asciiFallback and for normalize() (which must
# agree with sn_logic.normalize). The okina and the left single quote are dropped like apostrophes.
TRANSLIT = {
    "\u02bb": "", "\u2018": "", "\u2019": "'", "\u2013": "-", "\u2014": "-",
    "ß": "ss", "æ": "ae", "Æ": "AE", "ð": "d", "Ð": "D", "þ": "th", "Þ": "Th", "ø": "o", "Ø": "O",
    "Đ": "D", "đ": "d", "Ħ": "H", "ħ": "h", "ı": "i", "Ĳ": "IJ", "ĳ": "ij", "ĸ": "k", "Ŀ": "L", "ŀ": "l",
    "Ł": "L", "ł": "l", "ŉ": "n", "Ŋ": "N", "ŋ": "n", "Œ": "OE", "œ": "oe", "Ŧ": "T", "ŧ": "t", "ſ": "s",
}


def to_ascii(s: str) -> str:
    """ "Cañon City" -> "Canon City", "Utqiaġvik" -> "Utqiagvik", "Hawaiʻi" -> "Hawaii". Characters without an
    ASCII form stay as they are (the lint reports them)."""
    out = []
    for c in s:
        if c < "\x80":
            out.append(c)
        elif c in TRANSLIT:
            out.append(TRANSLIT[c])
        else:
            d = "".join(x for x in unicodedata.normalize("NFKD", c) if not unicodedata.combining(x))
            out.append(d if d.isascii() else c)
    return "".join(out)


