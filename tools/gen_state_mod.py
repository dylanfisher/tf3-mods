# Lint (same rules as templates/state_names/tests/test_data.lua)

def normalize(s: str) -> str:
    s = to_ascii(s).lower()
    s = s.replace("'", "")
    s = re.sub(r"[^0-9a-z#]+", " ", s)
    return s.strip()


def lint(key: str, state: dict, towns: list[dict], streets: list, cities: dict) -> list[str]:
    errs: list[str] = []
    min_towns = int(state.get("minTowns") or MIN_TOWNS)
    min_pool = int(state.get("minPool") or MIN_POOL)
    min_street_cities = int(state.get("minStreetCities") or MIN_STREET_CITIES)
    ascii_only = bool(state.get("asciiFallback"))

    def name_ok(s: object, where: str) -> None:
        if not isinstance(s, str) or not s:
            errs.append(f"{where}: empty or not a string")
            return
        if len(s.encode("utf-8")) > MAX_BYTES:
            errs.append(f"{where}: longer than {MAX_BYTES} bytes: {s}")
        if s != s.strip():
            errs.append(f"{where}: leading/trailing space: {s!r}")
        if ascii_only and not s.isascii():
            errs.append(f"{where}: not ASCII after transliteration (asciiFallback; add it to TRANSLIT): {s}")

    def list_ok(lst: object, where: str) -> None:
        if not isinstance(lst, list) or not lst:
            errs.append(f"{where}: empty or not a list")
            return
        seen = set()
        for i, s in enumerate(lst, 1):
            name_ok(s, f"{where}[{i}]")
            if isinstance(s, str):
                if normalize(s) in seen:
                    errs.append(f"{where}: duplicate {s}")
                seen.add(normalize(s))

    if len(towns) < min_towns:
        errs.append(f"towns.tsv: {len(towns)} towns, want >= {min_towns}")
    seen: set[str] = set()
    tags: set[str] = set()
    for i, t in enumerate(towns, 1):
        name_ok(t["n"], f"towns.tsv row {i}")
        if normalize(t["n"]) in seen:
            errs.append(f"towns.tsv: duplicate town {t['n']}")
        seen.add(normalize(t["n"]))
        if not t["t"]:
            errs.append(f"towns.tsv: {t['n']} has no tags")
        tags.update(t["t"])
    for climate, weights in (state.get("climates") or {}).items():
        for tag, w in weights.items():
            if tag not in tags:
                errs.append(f"state.lua climates.{climate}: unknown tag {tag}")
            if not isinstance(w, (int, float)) or w < 0:
                errs.append(f"state.lua climates.{climate}.{tag}: bad weight {w!r}")
        pool = sum(1 for t in towns if any(tag in weights for tag in t["t"]))
        if pool < min_pool:
            errs.append(f"state.lua climates.{climate}: pool of {pool} towns, want >= {min_pool}")
    for rs in state.get("regionalSets") or []:
        for tag in rs.get("tags") or []:
            if tag not in tags:
                errs.append(f"state.lua regionalSets.{rs.get('id')}: unknown tag {tag}")
    list_ok(streets, "streets.lua")
    with_streets = 0
    for city, entry in cities.items():
        names = [city] + list(entry.get("aliases") or [])
        if not any(normalize(n) in seen for n in names):
            errs.append(f"cities.lua: {city} is not a town in towns.tsv")
        for k in entry:
            if k not in KINDS and k != "aliases":
                errs.append(f"cities.lua {city}: unknown list {k}")
        base_streets = {normalize(s) for s in entry.get("streets") or []}
        for kind in KINDS:
            if kind in entry:
                list_ok(entry[kind], f"cities.lua {city}.{kind}")
                if kind != "streets":
                    for s in entry[kind]:
                        if isinstance(s, str) and normalize(s) in base_streets:
                            errs.append(f"cities.lua {city}: {s} is both a street and a {kind} name")
        if entry.get("streets"):
            with_streets += 1
    if with_streets < min_street_cities:
        errs.append(f"cities.lua: {with_streets} cities with streets, want >= {min_street_cities}")
    for tag in state.get("regionLabels") or {}:
        if tag not in tags:
            errs.append(f"state.lua regionLabels: unknown tag {tag}")
    return [f"{key}: {e}" for e in errs]


