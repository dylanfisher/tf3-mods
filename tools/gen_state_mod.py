def load_lua(path: Path) -> object:
    """Runs a data file (ours, committed) in a fresh Lua state and converts its return value to Python."""
    return load_lua_text(path.read_text(encoding="utf-8"))


def load_lua_text(text: str) -> object:
    lua = LuaRuntime(unpack_returned_tuples=False)
    return to_py(lua.execute(text), lua)


def to_py(v: object, lua: LuaRuntime) -> object:
    if lua.eval("type")(v) != "table":
        return v
    items = list(v.items())
    keys = [k for k, _ in items]
    if keys and all(isinstance(k, int) for k in keys) and sorted(keys) == list(range(1, len(keys) + 1)):
        return [to_py(v[i], lua) for i in range(1, len(keys) + 1)]
    if not keys:
        return {}
    return {k: to_py(val, lua) for k, val in items}


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_towns(path: Path) -> list[dict]:
    rows = []
    lines = path.read_text(encoding="utf-8").splitlines()
    head = lines[0].split("\t")
    for ln in lines[1:]:
        if not ln.strip():
            continue
        r = dict(zip(head, ln.split("\t")))
        rows.append({"n": r["name"], "t": [t for t in r["tags"].split(",") if t], "p": int(r["population"])})
    return rows


