"""Write Better Roundabouts' engine-tuned rule table from the probe search results.

Reads plans/square_roundabouts/probe_search.csv and probe_p5_search_jobs.csv (jobs),
probe_search_trials.csv (engine calls) and probe_results.csv / probe_p5_all.csv (the `all` /
`p5_all` sweeps of the shipped geometry), written by tools/parse_probe.py from the DEV-ONLY
probe's search subsets (PROBE.md "Search runs"),
and writes

  mods/square_roundabouts/content/infrastructure/street_construction/square_roundabouts_tuning.lua

which square_roundabouts_geometry.lua / _magic.lua read (geom.radiusFloor, geom.splitterRule,
magic.sizeFloor). Format: the comment at the top of the generated file.

  radius    from `radius` jobs without a fixed dev layout: per pattern (every searched axis but
            the radius) and probed slider radius r0 the ring radius to ship EXACTLY for sliders
            from r0 up to it (the smallest radius the engine accepted; every slider radius in
            between was tried and rejected). Written where the engine needs more than the
            offline growth shipped (`shipR`), where a sweep rejected the shipped radius and the
            search accepted a smaller one, and always for splitter patterns that follow a
            splitter rule (search_radius_split: the shipped layout there is new). 0 = keep the
            offline growth (the engine accepted the shipped radius or a smaller one: we do not
            shrink rings, safety first; or it accepted nothing up to the search maximum: a
            known gap, listed on stdout). Patterns whose cells are all 0 are left out.
  magic     from `magic_size` jobs: per arm road and direction, for each size the smallest
            accepted size at or above it (only where that is larger). Rows "armType,direction"
            for 1-lane satellites (search_magic), "armType,direction,2" for 2-lane ones
            (search_magic2; magic.sizeFloor falls back to the 1-lane row without one).
  splitter  from `splitter` trials (exact dev layouts at fixed radii, round rings plus one 2:1
            oval): per arm road one parameter set for every ring lane count, scored by looks
            (fork near 50 deg, short split, narrow legs, small spread, no neck) plus how far it
            makes the ring grow; rows per "arm,lanes" with `floor[layout]` = the smallest probed
            radius at which the engine accepted that set for the layout (and at every probed
            radius above it). Y takes the T floor and 5 arms the 6-arm floor (not probed). Where
            the engine accepted nothing for a layout, the floor is PROVISIONAL_FLOOR (stdout lists
            them; search_radius_split then searches the real radius).

Usage:
  uv run tools/gen_roundabouts_tuning.py [--jobs CSV] [--trials CSV] [--out LUA]
  uv run tools/gen_roundabouts_tuning.py --empty      # the neutral table (no engine data)
  uv run tools/gen_roundabouts_tuning.py --dry-run    # print, don't write
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from hubconfig import ROOT  # noqa: E402

PLANS = ROOT / "plans" / "square_roundabouts"
OUT = ROOT / "mods" / "square_roundabouts" / "content" / "infrastructure" / "street_construction" / "square_roundabouts_tuning.lua"
# main .con.lua param order of the probe's replay key m:<indices>
MAIN_ORDER = ["shape", "lanes", "radius", "arms", "splitter", "centre", "armType", "tram", "direction", "island", "signals"]
PATTERN = ["shape", "lanes", "arms", "splitter", "centre", "armType", "tram", "direction"]
# Magic replay key g:<indices>; "lanes" (satellite ring lanes) was appended later: a 4-value key = 1 lane
MAGIC_ORDER = ["size", "armType", "direction", "island", "lanes"]
RULE_FIELDS = [("split", "devSplit"), ("fork", "devFork"), ("spread", "devSpread"), ("leg", "devLeg"),
               ("neck", "devNeck"), ("neckType", "devNeckType")]

HEADER = """-- GENERATED by tools/gen_roundabouts_tuning.py: do not edit by hand.
-- Better Roundabouts: engine-tuned rules from the probe search (plans/square_roundabouts/PROBE.md).
{status}
--
-- radius[pattern][r0] = ring radius (m) to build exactly for slider radii from r0 up to it (the
--   smallest radius the engine accepted, searched from r0), or 0 = the offline growth rule
--   pattern = "shape,lanes,arms,splitter,centre,armType,tram,direction" (param indices), plus
--   ",throughType" (arm road index) for a road through the centre other than the arm road
-- inferred[pattern] = true: copied from the anticlockwise pattern (not searched clockwise)
-- magic["armType,direction"][size] = smallest size index the engine accepted
-- splitter["armType,lanes"] = {{ split = m, fork = deg, spread = m, leg = geom.DEV_LEGS index,
--   neck = m, neckType = arm road index, floor = {{ [arms layout] = smallest radius (m) }},
--   verified = {{ [arms layout] = true }} }}  (any subset; floor: the ring starts at that radius for
--   smaller slider radii; verified: the engine accepted the rule there on a round ring without a
--   through road or tram tracks, anticlockwise, so it is built there even if the offline model objects)
-- channel["layout,main,side,splitter"] = {{ angle = deg, slip = ch.SLIP_TEMPLATES index }}: the
--   Channelized Junction's slip lanes the engine accepted where 40 deg one-way xsmall was rejected,
--   or {{ none = true }}: nothing accepted yet (square_roundabouts_channel.lua ch.FALLBACK, unverified)
"""


THROUGH_SAME = 1   # geom.THROUGH_SAME: the through road follows the arm road
CENTRE_ROAD, CENTRE_ROAD_LIGHTS = 2, 4


def key_indices(key: str) -> tuple[str, list[int]]:
    """Tag and param indices of a replay key. Main keys got a 12th value (the through road,
    Phase 5c) after the first tables were built: a 12-value key with Same as arms (1) is the
    11-value key. Any other through road keeps its 12 values (pattern_of appends it to the pattern,
    Phase 5f). Road + traffic lights (centre 4) has the Road geometry: centre 2 (geom.patternKey)."""
    tag, _, rest = key.partition(":")
    idx = [int(x) for x in rest.split(",") if x]
    if tag == "m" and len(idx) == len(MAIN_ORDER) + 1 and idx[-1] == THROUGH_SAME:
        idx = idx[:-1]
    if tag == "m" and len(idx) >= len(MAIN_ORDER) and idx[MAIN_ORDER.index("centre")] == CENTRE_ROAD_LIGHTS:
        idx[MAIN_ORDER.index("centre")] = CENTRE_ROAD
    return tag, idx


def main_dict(idx: list[int]) -> dict[str, int] | None:
    """Axis values of a main key from key_indices (11 values, or 12 with another through road)."""
    if len(idx) == len(MAIN_ORDER):
        return dict(zip(MAIN_ORDER, idx))
    if len(idx) == len(MAIN_ORDER) + 1:
        return dict(zip(MAIN_ORDER + ["through"], idx))
    return None


def num(v: str | None) -> float | None:
    try:
        return float(v) if v not in (None, "", "-") else None
    except ValueError:
        return None


def lua_num(v: float) -> str:
    return str(int(v)) if float(v).is_integer() else repr(float(v))


def read_csv(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        return []
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def pattern_of(d: dict[str, int]) -> str:
    """Tuning pattern of a main combo (geom.patternKey): Arms None builds no splitter, so splitter
    on with Arms None is the splitter-off pattern; a road through the centre other than the arm
    road appends its arm road index (through road index - 1) as a ninth field."""
    d = dict(d)
    if d["arms"] == 6:
        d["splitter"] = 1
    key = ",".join(str(d[k]) for k in PATTERN)
    through = d.get("through", THROUGH_SAME)
    if d["centre"] == CENTRE_ROAD and through != THROUGH_SAME and through - 1 != d["armType"]:
        key += f",{through - 1}"
    return key


DIRECTION_FIELD = PATTERN.index("direction")


def with_direction(pattern: str, direction: int) -> str:
    """The pattern with another direction (1 anticlockwise, 2 clockwise)."""
    parts = pattern.split(",")
    parts[DIRECTION_FIELD] = str(direction)
    return ",".join(parts)


def direction_of(pattern: str) -> int:
    return int(pattern.split(",")[DIRECTION_FIELD])


def sweep_rejects(rows: list[dict[str, str]]) -> dict[tuple[str, int], float]:
    """(pattern, slider radius) -> shipped radius the `all` sweep saw rejected (main entry)."""
    out: dict[tuple[str, int], float] = {}
    for r in rows:
        if r.get("entry") != "main" or r.get("ok") == "true":
            continue
        tag, idx = key_indices(r.get("key", ""))
        eff = num(r.get("effR"))
        d = main_dict(idx) if tag == "m" else None
        if d is None or eff is None:
            continue
        out[(pattern_of(d), int(num(r.get("radius")) or 0))] = eff
    return out


def radius_table(jobs: list[dict[str, str]], rule_arms: set[int], sweep: dict[tuple[str, int], float]) -> tuple[dict[str, dict[int, float]], list[str]]:
    """Exact radii per pattern and probed slider radius (0 = offline growth); notes for stdout."""
    out: dict[str, dict[int, float]] = defaultdict(dict)
    mins: dict[tuple[str, int], float | None] = {}
    counts: dict[str, int] = defaultdict(int)
    gaps: list[str] = []
    for j in jobs:
        if j.get("kind") != "radius" or j.get("fixed") or j.get("skipped"):
            continue
        tag, idx = key_indices(j["key"])
        d = main_dict(idx) if tag == "m" else None
        if d is None:
            continue
        pattern = pattern_of(d)
        r0 = int(num(j.get("radius")) or 0)
        best = num(j.get("devRadius")) if j.get("found") == "true" else None
        ship = num(j.get("shipR"))
        rule = d["splitter"] == 2 and d["armType"] in rule_arms
        rejected = sweep.get((pattern, r0))
        mins[(pattern, r0)] = best
        if best is None:
            value = 0
            counts["none found (offline growth stays; known gap)"] += 1
            gaps.append(f"  none up to the search maximum: {j['key']} from {r0} m (ships {lua_num(ship) if ship else '?'} m)")
        elif rule:
            value = best
            counts["splitter rule pattern: exact engine radius"] += 1
        elif ship is None or best > ship:
            value = best
            counts["engine needs more than shipped: exact engine radius"] += 1
        elif rejected is not None and rejected != best:
            value = best
            counts["the sweep rejected the shipped radius, the search accepted less: exact engine radius"] += 1
        else:
            value = 0
            counts["engine accepts the shipped radius" + (" or smaller (not shrunk)" if best < ship else "")] += 1
            if rejected is not None:
                gaps.append(f"  sweep rejected {lua_num(rejected)} m, search accepted it: {j['key']} from {r0} m")
        out[pattern][r0] = value
    # clockwise: only the tram line was searched clockwise (search_tram); elsewhere the
    # anticlockwise cell is used, since the clockwise and anticlockwise minima agree
    searched = {p for p in out if direction_of(p) == 2}
    same = differ = 0
    for (p, r0), m in mins.items():
        if direction_of(p) == 2 and (with_direction(p, 1), r0) in mins:
            same += mins[(with_direction(p, 1), r0)] == m
            differ += mins[(with_direction(p, 1), r0)] != m
    inferred: set[str] = set()
    for p in [p for p in out if direction_of(p) == 1]:
        cw = with_direction(p, 2)
        if cw not in searched and any(v > 0 for v in out[p].values()):
            out[cw] = dict(out[p])
            inferred.add(cw)
    table = {p: v for p, v in out.items() if any(x > 0 for x in v.values())}
    INFERRED.clear()
    INFERRED.update(p for p in inferred if p in table)
    notes = [f"radius: {n} jobs: {what}" for what, n in sorted(counts.items())]
    notes.append(f"radius: clockwise vs anticlockwise minimum radius: {same} equal, {differ} differ; "
                 f"{len(inferred)} clockwise patterns inferred from anticlockwise")
    return table, notes + gaps


def magic_table(jobs: list[dict[str, str]]) -> dict[str, dict[int, int]]:
    out: dict[str, dict[int, int]] = {}
    for j in jobs:
        if j.get("kind") != "magic_size" or j.get("fixed"):
            continue
        tag, idx = key_indices(j["key"])
        if tag != "g":
            continue
        d = {"lanes": 1, **dict(zip(MAGIC_ORDER, idx))}
        accepted = sorted(int(x.split("=", 1)[1]) for x in (j.get("acceptedList") or "").split("|") if "=" in x)
        row = {}
        for size in range(1, 6):
            at_or_above = [a for a in accepted if a >= size]
            if at_or_above and at_or_above[0] > size:
                row[size] = at_or_above[0]
        # a probed 2-lane row is written even when empty: it then replaces the 1-lane fallback
        # (magic.sizeFloor), which would otherwise force the 1-lane floors on 2-lane satellites
        if d["lanes"] != 1 and accepted:
            out[f"{d['armType']},{d['direction']},{d['lanes']}"] = row
        elif row:
            out[f"{d['armType']},{d['direction']}"] = row
    return out


# Channelized Junction replay key c:<indices> (square_roundabouts_channel.con.lua order)
CHANNEL_ORDER = ["layout", "main", "side", "slips", "splitter", "armLength", "direction", "island"]
# shipped channel tunables (ch.SLIP_ANGLE, ch.CORNER_GAP, ch.SLIP_FREE, one-way xsmall = 1)
CH_SHIPPED = {"chSlipAngle": 40.0, "chCornerGap": 7.0, "chSlipFree": 4.0, "chSlip": 1.0}


def parse_label(label: str) -> dict[str, float]:
    """'chSlipAngle=50 chCornerGap=7' -> {name: value}."""
    out = {}
    for part in label.split():
        name, _, v = part.partition("=")
        if num(v) is not None:
            out[name] = num(v)
    return out


def channel_table(jobs: list[dict[str, str]]) -> tuple[dict[str, dict], list[str]]:
    """Per "layout,main,side,splitter" (the slip lanes set, traffic side, arm length and islands
    never changed a verdict, p5_all): the accepted slip angle / template with the shipped corner gap
    and free length (those changed nothing), narrowest template first, then the smallest angle.
    No row where the shipped 40 deg xsmall slip lanes were accepted; {none} where nothing was."""
    accepted: dict[str, set[tuple[float, float]]] = defaultdict(set)
    tried: dict[str, int] = defaultdict(int)
    for j in jobs:
        if j.get("kind") != "grid" or j.get("entry") != "channel" or j.get("skipped"):
            continue
        tag, idx = key_indices(j["key"])
        if tag != "c" or len(idx) != len(CHANNEL_ORDER):
            continue
        d = dict(zip(CHANNEL_ORDER, idx))
        if d["slips"] == 3:
            continue  # no slip lanes: nothing to tune
        row = f"{d['layout']},{d['main']},{d['side']},{d['splitter']}"
        tried[row] += 1
        for lab in (j.get("acceptedList") or "").split("|"):
            v = {**CH_SHIPPED, **parse_label(lab)} if lab.strip() else None
            if v and v["chCornerGap"] == CH_SHIPPED["chCornerGap"] and v["chSlipFree"] == CH_SHIPPED["chSlipFree"]:
                accepted[row].add((v["chSlip"], v["chSlipAngle"]))
    out: dict[str, dict] = {}
    counts: dict[str, int] = defaultdict(int)
    for row in tried:
        acc = sorted(accepted[row])
        if (CH_SHIPPED["chSlip"], CH_SHIPPED["chSlipAngle"]) in acc:
            counts["shipped 40 deg xsmall accepted"] += 1
        elif acc:
            slip, angle = acc[0]
            out[row] = {"angle": angle} if slip == 1 else {"angle": angle, "slip": slip}
            counts["accepted angle / template written"] += 1
        else:
            out[row] = {"none": True}
            counts["nothing accepted (none: ch.FALLBACK, unverified)"] += 1
    notes = [f"channel: {n} rows: {what}" for what, n in sorted(counts.items())]
    return out, notes


LAYOUT = {"T": 1, "Y": 2, "4": 3, "5": 4, "6": 5}
LAYOUT_NAME = {v: k for k, v in LAYOUT.items()}
# layouts the splitter search did not probe take the floor of a probed one with as many or more
# arms nearby: Y (3 arms, 120 deg apart) from T (3 arms, 90 deg), 5 arms from 6 arms
LAYOUT_FROM = {2: 1, 4: 5}
# floor where the engine accepted the rule nowhere up to the largest probed radius (large arms on
# 6-arm 1/2-lane rings): the slider's top; search_radius_split then searches the real radius
PROVISIONAL_FLOOR = 60
# radius patterns copied from the anticlockwise search (radius_table); written as `inferred`
INFERRED: set[str] = set()
SHAPE_ROUND = 1


def looks(rule: dict) -> float:
    """Penalty for how a splitter looks: fork near 50 deg, short split, narrow legs, small spread, no neck."""
    fork = rule.get("fork", 50)
    cost = (50 - fork) / 3 if fork < 50 else (fork - 50) * 4 / 3
    cost += (rule.get("leg", 1) - 1) * 5 + (rule.get("spread", 6) - 6) + (rule.get("split", 20) - 20)
    cost += 100 if (rule.get("neck") or 0) > 0 else 0
    return cost


def splitter_table(trials: list[dict[str, str]]) -> tuple[dict[str, dict], list[str]]:
    # arm -> lanes -> (layout, shape, radius) -> label -> ok
    by: dict[int, dict[int, dict[tuple[int, int, float], dict[str, bool]]]] = defaultdict(lambda: defaultdict(lambda: defaultdict(dict)))
    rules: dict[str, tuple[int, dict]] = {}
    for t in trials:
        if t.get("kind") != "splitter":
            continue
        tag, idx = key_indices(t["key"])
        if tag != "m":
            continue
        d = dict(zip(MAIN_ORDER, idx))
        r = num(t.get("devRadius"))
        if r is None:
            continue
        lab = t.get("label", "")
        rules.setdefault(lab, (int(t.get("cand") or 0), {name: num(t.get(col)) for name, col in RULE_FIELDS if num(t.get(col)) is not None}))
        by[d["armType"]][d["lanes"]][(d["arms"], d["shape"], r)][lab] = t.get("ok") == "true"

    def floor_of(bases: dict, layout: int, lab: str) -> float | None:
        """Smallest probed round radius accepted with lab, accepted at every probed radius above it too."""
        radii = sorted(r for (lay, shape, r) in bases if lay == layout and shape == SHAPE_ROUND)
        best = None
        for r in reversed(radii):
            if bases[(layout, SHAPE_ROUND, r)].get(lab):
                best = r
            else:
                break
        return best

    out: dict[str, dict] = {}
    notes: list[str] = []
    for arm in sorted(by):
        lanes_bases = by[arm]
        scored = []
        for lab, (cand, rule) in rules.items():
            cost = looks(rule)
            for lanes, bases in lanes_bases.items():
                for layout in sorted({lay for (lay, shape, _r) in bases if shape == SHAPE_ROUND}):
                    floors = [f for f in (floor_of(bases, layout, x) for x in rules) if f is not None]
                    mine = floor_of(bases, layout, lab)
                    if floors and mine is None:
                        cost += 100  # fails where another set works
                    elif mine is not None:
                        cost += 0.5 * (mine - min(floors))
                for (lay, shape, r), labs in bases.items():
                    if shape != SHAPE_ROUND and any(labs.values()) and not labs.get(lab):
                        cost += 10
            scored.append((cost, cand, lab, rule))
        scored.sort(key=lambda x: (x[0], x[1]))
        cost, _cand, lab, rule = scored[0]
        notes.append(f"splitter arm {arm}: {lab} (score {cost:.1f}; next: "
                     + ", ".join(f"{x[2]} {x[0]:.1f}" for x in scored[1:4]) + ")")
        for lanes, bases in sorted(lanes_bases.items()):
            floor: dict[int, float] = {}
            tried = accepted = 0
            verified: dict[int, bool] = {}
            for layout in sorted({lay for (lay, shape, _r) in bases if shape == SHAPE_ROUND}):
                f = floor_of(bases, layout, lab)
                if f is None:
                    f = PROVISIONAL_FLOOR
                    notes.append(f"  arm {arm} lanes {lanes} {LAYOUT_NAME[layout]}: no probed radius accepted, PROVISIONAL floor {f} m")
                else:
                    verified[layout] = True
                floor[layout] = f
                for (lay, shape, r), labs in bases.items():
                    if lay == layout and shape == SHAPE_ROUND and r >= f and lab in labs:
                        tried += 1
                        accepted += labs[lab]
            for layout, src in LAYOUT_FROM.items():
                if layout not in floor and src in floor:
                    floor[layout] = floor[src]
            row = dict(rule, floor=floor, verified=verified, rate=round(accepted / tried, 3) if tried else 0)
            out[f"{arm},{lanes}"] = row
            notes.append(f"  arm {arm} lanes {lanes}: floors " + ", ".join(f"{LAYOUT_NAME[k]}={lua_num(v)}" for k, v in sorted(floor.items()))
                         + f"; accepted {accepted}/{tried} at or above the floors")
    return out, notes


def render(status: str, radius: dict, magic: dict, splitter: dict, channel: dict | None = None) -> str:
    lines = [HEADER.format(status=status).rstrip("\n"), "", "return {", "\tversion = 2,", f"\tsource = {status_src(status)},"]
    if radius:
        lines.append("\tradius = {")
        for p in sorted(radius, key=pattern_sort):
            cells = ", ".join(f"[{r0}] = {lua_num(v)}" for r0, v in sorted(radius[p].items()))
            lines.append(f'\t\t["{p}"] = {{ {cells} }},')
        lines.append("\t},")
    else:
        lines.append("\tradius = {},")
    if INFERRED:
        lines.append("\t-- clockwise patterns not searched: the anticlockwise cells (the offline model must accept them)")
        lines.append("\tinferred = {")
        for p in sorted(INFERRED, key=pattern_sort):
            lines.append(f'\t\t["{p}"] = true,')
        lines.append("\t},")
    if magic:
        lines.append("\tmagic = {")
        if any(k.count(",") == 2 for k in magic):
            lines.append('\t\t-- "armType,direction,2": 2-lane satellites (search_magic2)')
        for k in sorted(magic):
            cells = ", ".join(f"[{s}] = {v}" for s, v in sorted(magic[k].items()))
            lines.append(f'\t\t["{k}"] = {{ {cells} }},' if cells else f'\t\t["{k}"] = {{}},')
        lines.append("\t},")
    else:
        lines.append("\tmagic = {},")
    if splitter:
        lines.append("\tsplitter = {")
        for k in sorted(splitter):
            r = splitter[k]
            cells = ", ".join(f"{name} = {lua_num(r[name])}" for name in [n for n, _ in RULE_FIELDS] + ["rate"] if name in r)
            if r.get("floor"):
                cells += ", floor = { " + ", ".join(f"[{k}] = {lua_num(v)}" for k, v in sorted(r["floor"].items())) + " }"
            if r.get("verified"):
                cells += ", verified = { " + ", ".join(f"[{k}] = true" for k in sorted(r["verified"])) + " }"
            lines.append(f'\t\t["{k}"] = {{ {cells} }},')
        lines.append("\t},")
    else:
        lines.append("\tsplitter = {},")
    if channel:
        lines.append("\tchannel = {")
        for k in sorted(channel, key=lambda x: [int(v) for v in x.split(",")]):
            r = channel[k]
            if r.get("none"):
                lines.append(f'\t\t["{k}"] = {{ none = true }},')
            else:
                cells = ", ".join(f"{name} = {lua_num(r[name])}" for name in ("angle", "slip") if name in r)
                lines.append(f'\t\t["{k}"] = {{ {cells} }},')
        lines.append("\t},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def pattern_sort(p: str) -> tuple[int, str]:
    """8-field patterns first in their old (string) order, then the through-road patterns."""
    return (p.count(","), p)


def status_src(status: str) -> str:
    text = status.removeprefix("-- ").replace('"', "'")
    return f'"{text}"'


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs", type=Path, nargs="+", default=[PLANS / "probe_search.csv", PLANS / "probe_p5_search_jobs.csv",
                             PLANS / "probe_p5f_search_jobs.csv"],
                    help="search job CSVs (parse_probe.py); missing files are skipped")
    ap.add_argument("--trials", type=Path, default=PLANS / "probe_search_trials.csv")
    ap.add_argument("--sweep", type=Path, nargs="+", default=[PLANS / "probe_results.csv", PLANS / "probe_p5_all.csv", PLANS / "probe_p5f_all.csv",
                             PLANS / "probe_p5g_verify.csv"],
                    help="sweeps of the shipped geometry (`all`, `p5_all`; parse_probe.py)")
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--empty", action="store_true", help="write the neutral table")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    if args.empty:
        text = render("-- Neutral table: no engine search data is baked in yet, so the geometry behaves as without it.", {}, {}, {})
        notes = []
    else:
        job_files = [(path, read_csv(path)) for path in args.jobs]
        jobs = [j for _path, rows in job_files for j in rows]
        trials = read_csv(args.trials)
        if not jobs and not trials:
            raise SystemExit(f"{', '.join(str(p) for p in args.jobs)}: no search results (run a search subset and tools/parse_probe.py; --empty for the neutral table)")
        splitter, split_notes = splitter_table(trials)
        rule_arms = {int(k.split(",")[0]) for k in splitter}
        sweep = sweep_rejects([r for path in args.sweep for r in read_csv(path)])
        radius, radius_notes = radius_table(jobs, rule_arms, sweep)
        magic = magic_table(jobs)
        channel, channel_notes = channel_table(jobs)
        status = ("-- From " + " + ".join(f"{path.name} ({len(rows)} jobs)" for path, rows in job_files if rows)
                  + f" and {args.trials.name} ({len(trials)} engine calls).")
        text = render(status, radius, magic, splitter, channel)
        notes = [f"radius: {len(radius)} patterns with an exact engine radius", *radius_notes, *channel_notes,
                 f"magic: {len(magic)} rows ({sum(1 for k in magic if k.count(',') == 2)} for 2-lane satellites)", *split_notes]
    for n in notes:
        print(n)
    if args.dry_run:
        print(text)
        return
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out.relative_to(ROOT) if args.out.is_relative_to(ROOT) else args.out}")


if __name__ == "__main__":
    main()
