"""Copy the mod.io mods you are subscribed to into .cache/subscribed/ for reference.

The game's mod.io client keeps subscriptions in
  <mod.io>/10640/<userId>/user.json            ("subscriptions": [modioId, ...])
and downloads them to
  <mod.io>/common/10640/mods/<modioId>/          (mod root with mod.json)
with names and versions in <mod.io>/common/10640/metadata/state.json.

Each subscribed, downloaded mod is copied to .cache/subscribed/<modId>/
(gitignored: third-party content) and listed in .cache/subscribed/INDEX.md.
The cache is rebuilt from scratch on every run. Only the "subscriptions" key of
user.json is read; the auth token in that file is never touched.

Copies are not linked into the staging area: a staging mod with the same modId
would override the subscribed one in game.

Usage: uv run tools/sync_subscribed.py
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from hubconfig import MODIO_GAME_ID, SUBSCRIBED_CACHE_DIR, modio_dir  # noqa: E402

# Per-machine caches the game writes into mod folders; not part of the mod.
SKIP_NAMES = {"texture_metadata_cache.lua", ".DS_Store"}


def subscriptions(root: Path) -> list[int]:
    ids: set[int] = set()
    for user_json in (root / MODIO_GAME_ID).glob("*/user.json"):
        ids.update(json.loads(user_json.read_text()).get("subscriptions", []))
    return sorted(ids)


def profiles(root: Path) -> dict[int, dict]:
    state = root / "common" / MODIO_GAME_ID / "metadata" / "state.json"
    if not state.exists():
        return {}
    return {m["ID"]: m.get("Profile", {}) for m in json.loads(state.read_text()).get("Mods", [])}


def mod_id(mod_dir: Path) -> str | None:
    mod_json = mod_dir / "mod.json"
    if not mod_json.exists():
        return None
    try:
        return json.loads(mod_json.read_text(encoding="utf-8-sig")).get("modId")
    except json.JSONDecodeError:
        return None


def main() -> None:
    root = modio_dir()
    subs = subscriptions(root)
    info = profiles(root)
    downloads = root / "common" / MODIO_GAME_ID / "mods"

    if SUBSCRIBED_CACHE_DIR.exists():
        shutil.rmtree(SUBSCRIBED_CACHE_DIR)
    SUBSCRIBED_CACHE_DIR.mkdir(parents=True)

    rows, missing = [], []
    for modio_id in subs:
        src = downloads / str(modio_id)
        profile = info.get(modio_id, {})
        name = profile.get("name", "?")
        if not src.is_dir():
            missing.append(f"{modio_id} ({name}): subscribed but not downloaded yet")
            continue
        folder = mod_id(src) or f"modio_{modio_id}"
        shutil.copytree(src, SUBSCRIBED_CACHE_DIR / folder, ignore=shutil.ignore_patterns(*SKIP_NAMES))
        mod_json = json.loads((src / "mod.json").read_text(encoding="utf-8-sig")) if (src / "mod.json").exists() else {}
        version = (profile.get("modfile") or {}).get("version") or ""
        author = (profile.get("submitted_by") or {}).get("username", "")
        rows.append((folder, name, author, modio_id, mod_json.get("revision", ""), version,
                     profile.get("profile_url", ""), profile.get("summary", "")))
        print(f"  {folder:32} {name}")

    lines = [
        "# Subscribed mods",
        "",
        "Generated by `make subscribed` from the mod.io client data. Third-party content: reference only.",
        "",
        "| Folder (modId) | Name | Author | mod.io id | revision | version | Summary |",
        "|---|---|---|---|---|---|---|",
    ]
    for folder, name, author, modio_id, rev, version, url, summary in rows:
        link = f"[{name}]({url})" if url else name
        lines.append(f"| `{folder}` | {link} | {author} | {modio_id} | {rev} | {version} | {summary} |")
    if missing:
        lines += ["", "Not downloaded:", *[f"- {m}" for m in missing]]
    (SUBSCRIBED_CACHE_DIR / "INDEX.md").write_text("\n".join(lines) + "\n")

    print(f"Copied {len(rows)} of {len(subs)} subscribed mods to {SUBSCRIBED_CACHE_DIR}")
    for m in missing:
        print(f"  missing: {m}")


if __name__ == "__main__":
    main()
