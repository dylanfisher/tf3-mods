"""Extract greppable text resources from the local Transport Fever 3 install.

The game ships most content inside .zip archives (each archive `x.zip` holds a
top-level folder `x/` that maps onto the resource path next to it). This script
copies loose text files and extracts only the text entries of every archive
into .cache/game/ (gitignored), preserving resource paths, e.g.
  base/content/vehicle/waggon/viaggio.zip:viaggio/viaggio.mdl
    -> .cache/game/base/content/vehicle/waggon/viaggio/viaggio.mdl

It also writes docs/game/MANIFEST.txt and docs/game/INDEX.md (committed) so a
game update shows up as a git diff.

Usage: uv run tools/sync_game.py
"""

from __future__ import annotations

import re
import shutil
import sys
import zipfile
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from hubconfig import GAME_CACHE_DIR, GAME_DOCS_DIR, STEAM_APP_ID, game_install, is_text_resource  # noqa: E402

# Install subtrees to index. Everything else is binaries/libraries.
SOURCES = ["api", "base/tealdef", "base/content", "base/mod.json", "base/_content.json", "mods", "vscode-template"]


def build_id(install: Path) -> str:
    manifest = install.parent.parent / f"appmanifest_{STEAM_APP_ID}.acf"
    if manifest.exists():
        match = re.search(r'"buildid"\s+"(\d+)"', manifest.read_text())
        if match:
            return match.group(1)
    return "unknown"


def extract_zip(archive: Path, install: Path, out: Path) -> list[tuple[str, int]]:
    written = []
    base = out / archive.parent.relative_to(install)
    with zipfile.ZipFile(archive) as zf:
        for info in zf.infolist():
            if info.is_dir() or not is_text_resource(info.filename):
                continue
            target = (base / info.filename).resolve()
            if out.resolve() not in target.parents:
                continue  # guard against path traversal
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(zf.read(info))
            written.append((target.relative_to(out.resolve()).as_posix(), info.file_size))
    return written


def main() -> None:
    install = game_install()
    out = GAME_CACHE_DIR
    staging = out.with_name(out.name + ".tmp")
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)

    files: list[tuple[str, int]] = []
    archives: list[Path] = []
    for source in SOURCES:
        root = install / source
        candidates = [root] if root.is_file() else sorted(p for p in root.rglob("*") if p.is_file())
        for path in candidates:
            if path.suffix.lower() == ".zip":
                archives.append(path)
            elif is_text_resource(path.name):
                rel = path.relative_to(install)
                (staging / rel).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(path, staging / rel)
                files.append((rel.as_posix(), path.stat().st_size))

    print(f"Copied {len(files)} loose files; scanning {len(archives)} archives …")
    bad: list[str] = []

    def work(archive: Path) -> list[tuple[str, int]]:
        try:
            return extract_zip(archive, install, staging)
        except zipfile.BadZipFile:
            bad.append(str(archive.relative_to(install)))
            return []

    with ThreadPoolExecutor(max_workers=8) as pool:
        for result in pool.map(work, archives):
            files.extend(result)

    shutil.rmtree(out, ignore_errors=True)
    staging.rename(out)

    files.sort()
    GAME_DOCS_DIR.mkdir(parents=True, exist_ok=True)
    (GAME_DOCS_DIR / "MANIFEST.txt").write_text("".join(f"{size}\t{path}\n" for path, size in files))

    by_ext = Counter(Path(p).name.split(".", 1)[-1] if "." in Path(p).name else "" for p, _ in files)
    by_dir = Counter("/".join(p.split("/")[:3]) for p, _ in files)
    lines = [
        "# TF3 Game Files Index",
        "",
        "Generated by `tools/sync_game.py`. Do not edit by hand; run `make docs-game`.",
        "",
        f"- Steam build id: `{build_id(install)}`",
        f"- Text files extracted: {len(files)} (from {len(archives)} archives + loose files)",
        "- Extracted copies live in `.cache/game/` (gitignored), mirroring install paths.",
        "- `MANIFEST.txt` lists every extracted file with its size (`size<TAB>path`).",
        "",
        "## Where to look",
        "",
        "- `api/tealdef/` — Teal type definitions for the scripting API (`api.res`, `api.cmd`, `api.engine`, `api.gui`, …).",
        "- `base/tealdef/` — Teal definitions for base-game script modules.",
        "- `base/content/` — base-game resources: `.mdl` models, `.mtl` materials, `.script.tl`/`.lua` scripts, configs.",
        "- `mods/release/` — official Urban Games mods (campaign missions, `urbangames_no_costs`) — real-world mod examples.",
        "- `vscode-template/` — `tlconfig.lua` and `all_def.tl` for VS Code Teal setup.",
        "",
        "## Files per area",
        "",
        "| Area | Files |",
        "|---|---|",
        *[f"| `{d}` | {n} |" for d, n in sorted(by_dir.items())],
        "",
        "## Files per type",
        "",
        "| Extension | Files |",
        "|---|---|",
        *[f"| `.{e}` | {n} |" for e, n in by_ext.most_common()],
        "",
    ]
    (GAME_DOCS_DIR / "INDEX.md").write_text("\n".join(lines))
    print(f"Extracted {len(files)} text files to {out}")
    if bad:
        print(f"WARNING: unreadable archives: {', '.join(bad)}", file=sys.stderr)


if __name__ == "__main__":
    main()
