-- refund_logic.tl: window param, ledger add/take/prune, owed and credit.

local logic = ug_require "square_full_refund::/refund/refund_logic.tl"

local function st(ledger) return logic.normalize({ v = 1, ledger = ledger or {} }) end

test("windowSeconds: seconds from mod.json numbers, 0-based index fallback, default 60", function()
	eq(logic.windowSeconds(60), 60)
	eq(logic.windowSeconds(120), 120)
	eq(logic.windowSeconds(600), 600)
	eq(logic.windowSeconds(0), 60)
	eq(logic.windowSeconds(1), 120)
	eq(logic.windowSeconds(3), 600)
	eq(logic.windowSeconds(4), 600)
	eq(logic.windowSeconds(nil), 60)
	eq(logic.windowSeconds("x"), 60)
	eq(logic.windowSeconds(5000), 60)
	eq(logic.windowSeconds(-1), 60)
end)

test("normalize: nil, garbage and old versions give an empty state", function()
	eq(logic.normalize(nil), { v = 1, ledger = {} })
	eq(logic.normalize({ v = 0, ledger = {} }), { v = 1, ledger = {} })
	eq(logic.normalize({ v = 1 }), { v = 1, ledger = {} })
	local s = { v = 1, ledger = { { e = 1, c = 2, t = 3 } } }
	ok(logic.normalize(s) == s, "valid state kept")
end)

test("add splits the cost, remainder to the first entity; rebuilt entity keeps one entry", function()
	local s = st()
	logic.add(s, { 10, 11, 12 }, 100, 5000)
	eq(s.ledger, { { e = 10, c = 34, t = 5000 }, { e = 11, c = 33, t = 5000 }, { e = 12, c = 33, t = 5000 } })
	logic.add(s, { 11 }, 50, 6000)
	eq(#s.ledger, 3)
	eq(s.ledger[3], { e = 11, c = 50, t = 6000 })
	eq(logic.add(s, { 20 }, 0, 1), {})
	eq(logic.add(s, {}, 10, 1), {})
	eq(#s.ledger, 3)
end)

test("take removes and returns only the wanted entities", function()
	local s = st({ { e = 1, c = 10, t = 0 }, { e = 2, c = 20, t = 0 }, { e = 3, c = 30, t = 0 } })
	eq(logic.take(s, { 3, 1, 99 }), { { e = 1, c = 10, t = 0 }, { e = 3, c = 30, t = 0 } })
	eq(s.ledger, { { e = 2, c = 20, t = 0 } })
end)

test("prune drops expired entries and caps the ledger at 400", function()
	local s = st({ { e = 1, c = 10, t = 0 }, { e = 2, c = 20, t = 50000 } })
	eq(logic.prune(s, 61000, 60000), 1)
	eq(s.ledger, { { e = 2, c = 20, t = 50000 } })
	local big = {}
	for i = 1, 450 do big[i] = { e = i, c = 1, t = 0 } end
	s = st(big)
	eq(logic.prune(s, 0, 60000), 50)
	eq(#s.ledger, 400)
	eq(s.ledger[1].e, 51)
end)

test("owed counts only entries inside the window", function()
	local owed, hits = logic.owed({ { e = 1, c = 100, t = 0 }, { e = 2, c = 40, t = 70000 } }, 120000, 60000)
	eq(owed, 40)
	eq(hits, 1)
	eq({ logic.owed({}, 0, 60000) }, { 0, 0 })
end)

test("credit = owed - engine refund, never negative, never above owed", function()
	eq(logic.credit(1084412, 813306), 271106)
	eq(logic.credit(1000, 1000), 0)
	eq(logic.credit(1000, 1200), 0)
	eq(logic.credit(1000, 0), 1000)
	eq(logic.credit(1000, -50), 1000)
	eq(logic.credit(0, 0), 0)
	eq(logic.credit(nil, 0), 0)
end)

test("fingerprint is order-independent; classify", function()
	eq(logic.fingerprint({ 3, 1, 2 }), logic.fingerprint({ 1, 2, 3 }))
	ok(logic.fingerprint({ 1, 2 }) ~= logic.fingerprint({ 1, 3 }))
	eq(logic.fingerprint({}), "0:0:0:0")
	eq(logic.classify(1, 0), "add")
	eq(logic.classify(0, 2), "remove")
	eq(logic.classify(1, 1), "rebuild")
	eq(logic.classify(0, 0), "none")
end)

test("edgeKey: order-independent, 0.1 m, 'e:' prefix; sameEdge tolerant in both orientations", function()
	local k1, g1 = logic.edgeKey({ 100, 0, 5 }, { 0.04, 0, 5 })
	local k2, g2 = logic.edgeKey({ 0.04, 0, 5 }, { 100, 0, 5 })
	eq(k1, k2)
	eq(k1, "e:0.0,0.0,5.0|100.0,0.0,5.0")
	eq(g1, g2)
	ok(logic.sameEdge(g1, { 100.4, 0.3, 5, 0, -0.2, 5.1 }, 0.5), "reversed, within tolerance")
	ok(not logic.sameEdge(g1, { 0, 0, 5, 100, 0.6, 5 }, 0.5), "0.6 m off")
	ok(not logic.sameEdge(g1, nil, 0.5))
end)

test("split: proportional, sums to cost, remainder to the longest (first on a tie); equal split for zero weights", function()
	eq(logic.split({ 100, 100, 100 }, 179156), { 59720, 59718, 59718 })
	eq(logic.split({ 300, 100 }, 4000), { 3000, 1000 })
	eq(logic.split({ 0, 0 }, 5), { 3, 2 })
	eq(logic.split({}, 5), {})
end)

test("addEdges/takeEdges: one entry per segment; rebuilt in place replaces; constructions untouched", function()
	local s = st({ { e = 7, c = 10, t = 0 } })
	local a = { p0 = { 0, 0, 0 }, p1 = { 10, 0, 0 }, len = 10 }
	local b = { p0 = { 10, 0, 0 }, p1 = { 20, 0, 0 }, len = 30 }
	logic.addEdges(s, { a, b }, 400, 100)
	eq(#s.ledger, 3)
	eq(s.ledger[2].c, 100)
	eq(s.ledger[3].c, 300)
	logic.addEdges(s, { a }, 50, 200)
	eq(#s.ledger, 3)
	eq(s.ledger[3].c, 50)
	local taken = logic.takeEdges(s, { { p0 = { 10.2, 0, 0 }, p1 = { 0, 0.1, 0 } } })
	eq(#taken, 1)
	eq(taken[1].c, 50)
	eq(logic.take(s, { 7 })[1].c, 10)
	eq(#s.ledger, 1)
	eq(logic.addEdges(s, { a }, 0, 1), {})
end)
