test("every profile resolves with the full schema", function()
	for _, id in ipairs(ST.IDS) do
		local p = ST.profile(id)
		eq(p.id, id)
		for _, k in ipairs({ "grower", "block", "gridness", "jitter", "curve", "arterialEvery", "templates",
			"maxSlope", "contour", "waterSetback", "stationPull", "lead", "ribbon", "angleRange", "weights" }) do
			ok(p[k] ~= nil, id .. "." .. k)
		end
		ok(p.block.len > 0 and p.block.depth > 0)
		for _, c in ipairs(ST.CLASSES) do ok(p.templates[c], id .. " template " .. c) end
	end
	eq(ST.profile("NOPE"), nil)
	-- profiles are copies
	ST.profile("NA_GRID").block.len = 1
	eq(ST.profile("NA_GRID").block.len, 200)
end)

