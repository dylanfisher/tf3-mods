test("resolve: templates by year, outer zones by era, modifiers", function()
	local p = F.style({ year = 1939 })
	eq(p.templatePaths.main, "::/infrastructure/street/town/town_old_medium.street_template")
	eq(p.templatePaths.small, "::/infrastructure/street/town/town_old_small.street_template")
	eq(F.style({ year = 1940 }).templatePaths.main, "::/infrastructure/street/town/town_new_medium.street_template")
	eq(F.style({ nameList = "::/names/japan/x", year = 1990 }).templatePaths.small,
		"::/infrastructure/street/town/town_new_xsmall.street_template")
	eq(F.style({ year = 1960 }).outer.id, "NA_SUBURB")
	eq(F.style({ year = 1930 }).outer, nil)
	-- (era range 1900+: the EU organic town's extension ring from 1915, ot_style EXT_OUTER_YEAR)
	eq(F.style({ nameList = "::/names/germany/x", year = 1920 }).outer.id, "EU_EXTENSION")
	eq(F.style({ nameList = "::/names/germany/x", year = 1900 }).outer, nil)
	eq(F.style({ nameList = "::/names/germany/x", year = 1920, forceStyle = "EU_ORGANIC" }).outer, nil)
	local sub = F.style({ nameList = "::/names/norway/x", climate = "subarctic" })
	near(sub.block.len, 190 * 1.2, 1e-9)
	near(F.style({ nameList = "::/names/oceania/x" }).block.depth, 120, 1e-9)
	local small = F.style({ nameList = "::/names/germany/x", capacity = 100 })
	eq(small.radial.spokes, 4)
	eq(F.style({ nameList = "::/names/germany/x", capacity = 3000 }).radial.spokes, 6)
	eq(F.style({ capacity = 100, year = 1930 }).arterialEvery, 16)
	-- late hierarchy (1960): arterials every 6 blocks, collectors every 2, both doubled in a small town
	local late = F.style({ capacity = 100 })
	eq(late.arterialEvery, 12)
	eq(late.collectorEvery, 4)
	eq(F.style({ capacity = 3000 }).arterialEvery, 6)
end)

test("resolve: axis from seed / water / station / existing streets", function()
	local na = F.style({})
	eq(na.axisSource, "seed")
	eq(na.axis, 0, "NA angleRange 0")
	local eu = F.style({ nameList = "::/names/germany/x", shape = "compact" })
	ok(math.abs(math.deg(eu.axis)) <= 15, "EU within +/- angleRange/2 (a compact town keeps its seeded axis)")
	local wet = F.style({}, F.coast(300))
	eq(wet.axisSource, "water")
	ok(G.lineAngleDiff(wet.axis, math.pi / 2) < math.rad(10))
	eq(wet.waterfront, true)
	local jp = F.style({ nameList = "::/names/japan/x", stations = { { 300, 300 } } })
	eq(jp.axisSource, "station")
	near(jp.axis, math.pi / 4, 1e-9)
	-- existing streets win, turned by 90 deg steps toward the fresh axis
	local s = F.style({ nameList = "::/names/japan/x", stations = { { 0, 300 } }, axis = { angle = math.rad(-5), strength = 0.9 } })
	eq(s.axisSource, "streets")
	near(math.deg(s.axis), 85, 1e-9)
	local weak = F.style({ axis = { angle = math.rad(20), strength = 0.2 } })
	eq(weak.axisSource, "seed")
end)

test("resolve: MED hill town centre moves to a nearby hilltop", function()
	local p = F.style({ nameList = "::/names/italy/x", climate = "dry" }, F.hill)
	eq(p.id, "MED_HILL")
	ok(G.dist(p.centre[1], p.centre[2], 300, 0) < 60)
	local q = F.style({ nameList = "::/names/italy/x", radius = 400 }, F.hill)
	eq(q.centre, { 0, 0 }, "a grown town keeps its centre")
end)

test("zone: outer profile beyond its radius, resolved fields carried over", function()
	local p = F.style({ year = 1960 })
	eq(ST.zone(p, 100), p)
	local o = ST.zone(p, 900)
	eq(o.id, "NA_SUBURB")
	eq(o.axis, p.axis)
	eq(o.seed, p.seed)
	eq(o.templatePaths, p.templatePaths)
	eq(ST.zone(p, 901), o, "cached")
end)
