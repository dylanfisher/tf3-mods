-- ot_terrain

test("plane: gradient, slope, downhill and contour headings", function()
	local s = F.plane(0.08, math.rad(30))
	local gx, gy = T.gradient(s, 10, 20)
	near(gx, 0.08 * math.cos(math.rad(30)), 1e-9)
	near(gy, 0.08 * math.sin(math.rad(30)), 1e-9)
	near(T.slope(s, 0, 0), 0.08, 1e-9)
	near(G.angleDiff(T.downhill(s, 0, 0), math.rad(210)), 0, 1e-9)
	local c = T.contourHeading(s, 0, 0)
	near(G.lineAngleDiff(c, math.rad(120)), 0, 1e-9)
	-- the contour heading closest to a preferred heading
	near(G.angleDiff(T.contourHeading(s, 0, 0, math.rad(-60)), math.rad(-60)), 0, 1e-9)
	eq(T.contourHeading(F.flat, 0, 0), nil)
	eq(T.downhill(F.flat, 0, 0), nil)
end)

test("grades along paths", function()
	local s = F.plane(0.1, 0)
	near(T.grade(s, 0, 0, 100, 0), 0.1, 1e-9)
	near(T.grade(s, 0, 0, 0, 100), 0, 1e-9)
	near(T.pathMaxGrade(s, { { 0, 0 }, { 0, 100 }, { 100, 100 } }), 0.1, 1e-9)
	near(T.pathMaxGrade(F.hill, { { 0, 0 }, { 0, 10 } }), 0, 0.05)
end)

test("water: isWater from height, explicit water function, setback and clearance", function()
	local c = F.coast(300)
	ok(T.isWater(c, 301, 0))
	ok(not T.isWater(c, 299, 0))
	ok(T.wetAlong(c, { { 200, 0 }, { 320, 0 } }, 0))
	ok(not T.wetAlong(c, { { 200, -50 }, { 200, 50 } }, 25))
	ok(T.wetAlong(c, { { 285, -50 }, { 285, 50 } }, 25), "within the setback")
	ok(T.wetAlong(c, { { 200, 0 }, { 280, 0 } }, 25), "end runs on toward the water")
	eq(T.clearance(c, 0, 0, 200, 10), nil)
	eq(T.clearance(c, 260, 0, 200, 10), 50)
	eq(T.clearance(c, 400, 0), 0)
	local s = T.sampler(function() return 10 end, function(x, y) return x < 0 end)
	ok(T.isWater(s, -1, 0))
	ok(not T.isWater(s, 1, 0))
end)

test("stats: flat land", function()
	local st = T.stats(F.flat, 0, 0, 600, 24)
	near(st.meanSlope, 0, 1e-12)
	eq(st.waterFraction, 0)
	eq(st.water, nil)
	ok(st.samples > 400 and st.samples <= 576)
end)

test("stats: hillside relief points downhill, hilltop found", function()
	local st = T.stats(F.hill, 0, 0, 600, 24)
	ok(st.meanSlope > 0.05, "mean slope " .. st.meanSlope)
	ok(st.p95Slope >= st.meanSlope)
	ok(G.angleDiff(st.relief.dir, math.pi) < math.rad(10), "downhill to the west")
	ok(G.dist(st.high[1], st.high[2], 300, 0) < 60, "top near (300, 0)")
end)

test("stats: river vs coast", function()
	local r = T.stats(F.river(-120), 0, 0, 600, 24)
	eq(r.water.kind, "river")
	ok(G.lineAngleDiff(r.water.axis, 0) < math.rad(5), "bank runs east-west")
	ok(G.angleDiff(r.water.dir, -math.pi / 2) < math.rad(10), "water to the south")
	near(r.water.distance, 95, 15)
	local c = T.stats(F.coast(300), 0, 0, 600, 24)
	eq(c.water.kind, "coast")
	ok(G.angleDiff(c.water.dir, 0) < math.rad(10), "sea to the east")
	ok(G.lineAngleDiff(c.water.axis, math.pi / 2) < math.rad(10), "shore runs north-south")
	ok(c.waterFraction > 0.05 and c.waterFraction < 0.3)
end)

